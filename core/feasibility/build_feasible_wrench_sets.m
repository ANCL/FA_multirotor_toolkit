function sets = build_feasible_wrench_sets(model, options)
%BUILD_FEASIBLE_WRENCH_SETS Construct force, moment, and zero-moment sets.
%
% Syntax
%   sets = build_feasible_wrench_sets(model)
%   sets = build_feasible_wrench_sets(model, options)
%
% options.compute_force, options.compute_moment, and
% options.compute_zero_moment_force control the requested calculations.

if nargin < 2
    options = struct();
end
options = complete_options(options);
validate_allocation_model(model);
metadata = struct();
metadata.wrench_order = model.wrench_order;
metadata.actuator_bounds = model.actuator_bounds;
sets = struct('force',[],'moment',[],'zero_moment_force',[], ...
    'metadata',metadata);
if options.compute_force
    sets.force = zonotope_geometry( ...
        model.A_f,model.actuator_bounds,options.hull_tolerance);
end
if options.compute_moment
    sets.moment = zonotope_geometry( ...
        model.A_tau,model.actuator_bounds,options.hull_tolerance);
end
if options.compute_zero_moment_force
    sets.zero_moment_force = zero_moment_force_set( ...
        model.A_f,model.A_tau,model.actuator_bounds,options);
end
end

function options = complete_options(options)
defaults = struct( ...
    'compute_force',true, ...
    'compute_moment',true, ...
    'compute_zero_moment_force',true, ...
    'equality_tolerance',1e-8, ...
    'bound_tolerance',1e-9, ...
    'vertex_tolerance',1e-9, ...
    'hull_tolerance',1e-8);
fields = fieldnames(defaults);
for k = 1:numel(fields)
    if ~isfield(options,fields{k})
        options.(fields{k}) = defaults.(fields{k});
    end
end
end

function data = zonotope_geometry(A_sub, actuator_bounds, tolerance)
%ZONOTOPE_GEOMETRY Exact three-dimensional linear-image geometry.
%
%   data = zonotope_geometry(A_sub, actuator_bounds)
%   data = zonotope_geometry(A_sub, actuator_bounds, tolerance)
%
% Inputs
%   A_sub            - 3-by-N linear map, such as A_f or A_tau.
%   actuator_bounds  - [lower upper] or N-by-2 actuator bounds.
%   tolerance        - Optional positive geometry tolerance.
%
% Output
%   data contains vertices, affine dimension, generators, faces, and a
%   half-space representation when the set is three-dimensional.
%
%   This function avoids enumerating all 2^number_of_actuators actuator corners for the
%   full-dimensional 3D case. It exploits the 3D zonotope structure:
%   facet normals are generated by cross products of generator pairs.
%
%   The actuator box is converted to the centered zonotope
%
%       Z = center + sum_i [-g_i, g_i]
%
%   where center = A_sub * mu_mid and g_i = A_sub(:,i) * mu_rad_i.

    %% Input checks
    if nargin < 2
        error('fa:NotEnoughInputs', ...
            'zonotope_geometry requires A_sub and actuator_bounds.');
    end
    if nargin < 3
        tolerance = [];
    end

    validateattributes(A_sub,{'numeric'}, ...
        {'real','finite','nrows',3,'nonempty'});
    number_of_actuators = size(A_sub,2);

    [lb,ub,bounds] = parse_actuator_bounds( ...
        actuator_bounds,number_of_actuators);

    %% Convert actuator box to centered zonotope
    mu_mid = 0.5 * (lb + ub);
    mu_rad = 0.5 * (ub - lb);

    center = A_sub * mu_mid;
    G = A_sub * diag(mu_rad);

    % Remove zero generators for geometry construction, but keep original G.
    gen_norms = vecnorm(G, 2, 1);
    scale = max(1, norm(G, 'fro'));
    if isempty(tolerance)
        tol = 1e-10 * scale;
    else
        validateattributes(tolerance, {'numeric'}, ...
            {'real','finite','scalar','positive'});
        tol = tolerance;
    end

    active = gen_norms > tol;
    G_active = G(:, active);

    %% Determine affine dimension
    if isempty(G_active)
        affine_dim = 0;
        basis = zeros(3, 0);
    else
        [U, S, ~] = svd(G_active, 'econ');
        singular_values = diag(S);
        affine_dim = sum(singular_values > tol);
        basis = U(:, 1:affine_dim);
    end

    %% Build geometry depending on dimension
    faces = struct('vertices', {}, 'normal', {}, 'support', {});
    vertices = [];
    A = [];
    b = [];

    if affine_dim == 3
        [faces, A, b] = build_3d_zonotope_faces(center, G_active, tol);

        if ~isempty(faces)
            vertices = vertcat(faces.vertices);
            vertices = unique_rows_tol(vertices, 100 * tol);
        end

    elseif affine_dim == 2
        B = basis(:, 1:2);
        Q = B.' * G_active;
        P2 = zonotope_polygon_2d(Q, tol);
        vertices = center.' + (B * P2.').';

        % The zonotope lies in a plane. There is no basis(:,3) when the
        % affine dimension is exactly two, so compute a normal separately.
        n = null(B.');
        if isempty(n)
            n = [0; 0; 1];
        else
            n = n(:, 1);
        end

        faces(1).vertices = vertices;
        faces(1).normal = n;
        faces(1).support = NaN;

    elseif affine_dim == 1
        dir1 = basis(:, 1);
        q = dir1.' * G_active;
        radius = sum(abs(q));

        p1 = center - radius * dir1;
        p2 = center + radius * dir1;

        vertices = [p1.'; p2.'];

    else
        vertices = center.';
    end

    %% Package output
    data.A_sub = A_sub;
    data.actuator_bounds = bounds;

    data.center = center;
    data.generators = G;
    data.active_generators = G_active;

    data.affine_dimension = affine_dim;
    data.basis = basis;

    data.vertices = vertices;

    data.faces = faces;

    % Half-space representation for full-dimensional 3D cases:
    % A*x <= b
    data.halfspace_normals = A;
    data.halfspace_offsets = b;
    data.degenerate = affine_dim < 3;
end

%% ------------------------------------------------------------------------
function [faces, A, b] = build_3d_zonotope_faces(center, G, tol)
%BUILD_3D_ZONOTOPE_FACES Construct exact 3D zonotope facets.
%
% Facet normals of a 3D zonotope are perpendicular to pairs of generators.

    N = size(G, 2);

    normals = zeros(3, 0);
    normal_tol = 1e-8;

    % Candidate facet normals from generator pairs.
    for i = 1:N-1
        for j = i+1:N
            n = cross(G(:, i), G(:, j));
            n_norm = norm(n);

            if n_norm <= tol
                continue;
            end

            n = n / n_norm;
            n = canonical_normal(n);

            if isempty(normals)
                normals(:, end+1) = n;
            else
                dots = abs(normals.' * n);
                if all(dots < 1 - normal_tol)
                    normals(:, end+1) = n;
                end
            end
        end
    end

    faces = struct('vertices', {}, 'normal', {}, 'support', {});
    A = [];
    b = [];

    face_count = 0;

    % Each unique normal gives two opposite facets.
    for q = 1:size(normals, 2)
        for sgn = [-1, 1]
            n = sgn * normals(:, q);

            dot_vals = n.' * G;
            in_plane = abs(dot_vals) <= 100 * tol;

            % Support plane: n' x <= h
            h = n.' * center + sum(abs(dot_vals));

            % Facet center: fixed generators pushed to the supporting side.
            fixed_signs = sign(dot_vals);
            fixed_signs(in_plane) = 0;

            face_center = center + G * fixed_signs.';

            G_face = G(:, in_plane);

            % A true 3D facet should have a 2D in-plane generator span.
            if size(G_face, 2) < 2
                continue;
            end

            if rank(G_face, 100 * tol) < 2
                continue;
            end

            V_face = face_polygon_3d(face_center, G_face, n, tol);

            if size(V_face, 1) < 3
                continue;
            end

            face_count = face_count + 1;
            faces(face_count).vertices = V_face;
            faces(face_count).normal = n;
            faces(face_count).support = h;

            A = [A; n.']; %#ok<AGROW>
            b = [b; h];   %#ok<AGROW>
        end
    end
end

%% ------------------------------------------------------------------------
function V3 = face_polygon_3d(face_center, G_face, normal, tol)
%FACE_POLYGON_3D Ordered polygon vertices for one zonotope facet.

    % Build an orthonormal basis of the facet plane.
    B = null(normal.');

    if size(B, 2) ~= 2
        V3 = [];
        return;
    end

    % Project in-plane generators to 2D.
    Q = B.' * G_face;

    % Get ordered 2D zonotope polygon.
    P2 = zonotope_polygon_2d(Q, tol);

    if size(P2, 1) < 3
        V3 = [];
        return;
    end

    % Lift back to 3D.
    V3 = face_center.' + (B * P2.').';
end

%% ------------------------------------------------------------------------
function P = zonotope_polygon_2d(Q, tol)
%ZONOTOPE_POLYGON_2D Ordered vertices of a 2D zonotope.
%
% For Z = sum_i [-q_i, q_i], the boundary edges are generated by the
% vectors q_i and -q_i sorted by angle.

    if isempty(Q)
        P = [0, 0];
        return;
    end

    q_norms = vecnorm(Q, 2, 1);
    Q = Q(:, q_norms > tol);

    if isempty(Q)
        P = [0, 0];
        return;
    end

    if rank(Q, 100 * tol) < 2
        % Degenerate line segment in 2D.
        [U, ~, ~] = svd(Q, 'econ');
        d = U(:, 1);
        r = sum(abs(d.' * Q));

        P = [-r * d.'; r * d.'];
        return;
    end

    E = [Q, -Q].';
    angles = atan2(E(:, 2), E(:, 1));
    [~, idx] = sort(angles);
    E = E(idx, :);

    % Accumulate edge vectors.
    P = zeros(size(E, 1), 2);
    for k = 2:size(E, 1)
        P(k, :) = P(k-1, :) + 2 * E(k-1, :);
    end

    % Recenter around origin.
    P = P - mean(P, 1);

    % Remove repeated or nearly repeated vertices.
    P = unique_rows_tol(P, 100 * tol);

    % Reorder after duplicate removal, just in case.
    if size(P, 1) >= 3
        c = mean(P, 1);
        ang = atan2(P(:, 2) - c(2), P(:, 1) - c(1));
        [~, order] = sort(ang);
        P = P(order, :);
    end
end

%% ------------------------------------------------------------------------
function n = canonical_normal(n)
%CANONICAL_NORMAL Choose a unique sign for a normal direction.

    [~, idx] = max(abs(n));

    if n(idx) < 0
        n = -n;
    end
end

%% ------------------------------------------------------------------------
function U = unique_rows_tol(V, tol)
%UNIQUE_ROWS_TOL Stable approximate unique rows.

    if isempty(V)
        U = V;
        return;
    end

    if tol <= 0
        U = unique(V, 'rows', 'stable');
        return;
    end

    Vq = round(V / tol) * tol;
    [~, ia] = unique(Vq, 'rows', 'stable');
    U = V(ia, :);
end
