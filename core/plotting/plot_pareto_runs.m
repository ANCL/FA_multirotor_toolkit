function [fig, source_data] = plot_pareto_runs(all_runs, selected_summary)
%PLOT_PARETO_RUNS Plot all feasible runs with the Pareto front overlaid.
%
% The horizontal axis follows the signed minimization objective
% J_F = -r_F0, while the vertical axis is
% J_h = ||mu_h||_2^2. Smaller values are preferable on both axes.

style = publication_style();

% All feasible optimization outcomes.
all_J_F = -all_runs.r_F0;
all_J_h = all_runs.hover_effort;

% Selected nondominated points forming the reported front.
front_mask = selected_summary.nondominated & ...
    ~selected_summary.duplicate;

front_J_F = -selected_summary.r_F0(front_mask);
front_J_h = selected_summary.hover_effort(front_mask);

[front_J_F, order] = sort(front_J_F);
front_J_h = front_J_h(order);

if isempty(front_J_F)
    error('fa:EmptyParetoFront', ...
        'No selected nondominated points were found.');
end

fig = figure( ...
    'Units', 'centimeters', ...
    'Position', style.dimensions.column, ...
    'Color', style.colors.white);

ax = axes(fig);
hold(ax, 'on');

% Small background points showing every feasible run.
h(1) = plot( ...
    ax, all_J_F, all_J_h, '.', ...
    'Color', style.colors.gray, ...
    'MarkerSize', 4.5, ...
    'DisplayName', '$\mathrm{All\ feasible\ runs}$');

% Thin line and modest markers for the Pareto front.
h(2) = plot( ...
    ax, front_J_F, front_J_h, '-o', ...
    'Color', style.colors.blue, ...
    'LineWidth', 0.85, ...
    'MarkerSize', 3.5, ...
    'MarkerFaceColor', style.colors.white, ...
    'MarkerEdgeColor', style.colors.blue, ...
    'DisplayName', '$\mathrm{Pareto\ front}$');

xlabel(ax, '$J_{\mathrm F}=-r_{\mathcal F_0}(f_h)$');
ylabel(ax, '$J_{\mathrm h}=\|\mu_h\|_2^2$');

format_publication_axes(ax, 'quantitative');
axis(ax, 'padded');

legend( ...
    ax, h, ...
    'Location', 'northeast', ...
    'Orientation', 'vertical', ...
    'Interpreter', 'latex', ...
    'Box', 'off', ...
    'FontSize', style.font.legend);

source_data = struct();

source_data.all_runs = table( ...
    all_J_F, all_J_h, ...
    'VariableNames', {'J_F', 'J_h'});

source_data.pareto_front = table( ...
    front_J_F, front_J_h, ...
    'VariableNames', {'J_F', 'J_h'});
end