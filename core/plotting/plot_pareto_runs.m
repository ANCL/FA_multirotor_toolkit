function [fig, source_data] = plot_pareto_runs(all_runs, selected_summary)
%PLOT_PARETO_RUNS Plot all feasible runs with the Pareto front overlaid.
%
% The axes report the physical performance metrics directly: larger force
% authority is preferred, while smaller hover effort is preferred.

style = publication_style();

% All feasible optimization outcomes.
all_r_F0 = all_runs.r_F0;
all_hover_effort = all_runs.hover_effort;

% Selected nondominated points forming the reported front.
front_mask = selected_summary.nondominated & ...
    ~selected_summary.duplicate;

front_r_F0 = selected_summary.r_F0(front_mask);
front_hover_effort = selected_summary.hover_effort(front_mask);

[front_r_F0, order] = sort(front_r_F0);
front_hover_effort = front_hover_effort(order);

if isempty(front_r_F0)
    error('fa:EmptyParetoFront', ...
        'No selected nondominated points were found.');
end

fig = figure( ...
    'Units', 'centimeters', ...
    'Position', style.dimensions.column, ...
    'Color', style.colors.white);

ax = axes(fig);
hold(ax, 'on');

% Small background points showing every feasible optimization outcome.
h(1) = plot( ...
    ax, all_r_F0, all_hover_effort, '.', ...
    'Color', style.colors.black, ...
    'MarkerSize', 3.0, ...
    'DisplayName', '$\mathrm{All\ feasible\ runs}$');

% Every front point defines the line.
h(2) = plot( ...
    ax, front_r_F0, front_hover_effort, '-o', ...
    'Color', style.colors.blue, ...
    'LineWidth', 0.85, ...
    'MarkerSize', 2.0, ...
    'MarkerFaceColor', style.colors.white, ...
    'MarkerEdgeColor', style.colors.blue, ...
    'DisplayName', '$\mathrm{Pareto\ front}$');

xlabel(ax, '$r_{\mathcal F_0}(f_h)$');
ylabel(ax, '$\|\mu_h\|_2^2$');

format_publication_axes(ax, 'quantitative');
axis(ax, 'padded');

legend( ...
    ax, h, ...
    'Location', 'best', ...
    'Orientation', 'vertical', ...
    'Interpreter', 'latex', ...
    'Box', 'off', ...
    'FontSize', style.font.legend);

source_data = struct();

source_data.all_runs = table( ...
    all_r_F0, all_hover_effort, ...
    'VariableNames', {'r_F0', 'hover_effort'});

source_data.pareto_front = table( ...
    front_r_F0, front_hover_effort, ...
    'VariableNames', {'r_F0', 'hover_effort'});
end