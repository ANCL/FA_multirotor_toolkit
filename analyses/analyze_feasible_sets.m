function output = analyze_feasible_sets()
%ANALYZE_FEASIBLE_SETS Construct and export force and moment sets.
%
% Edit only the USER INPUTS section. For a complete configuration package,
% including geometry, allocation, hover, task, and manifest outputs, use
% analyze_configuration instead.

root = setup_project();
[parameters,solver] = study_settings();
[style,graphics_cleanup] = publication_style('activate'); %#ok<NASGU>
folder = ensure_folder(fullfile(root,'results','analyses','feasible_sets'));
study_log('open',fullfile(folder,'run_log.txt'));
cleanup = onCleanup(@() study_log('close')); %#ok<NASGU>
logger = study_log('stage_start','Analysis','Feasible-set analysis',1,0);
try
    %% USER INPUTS
    geometry = planar_shared_geometry([pi/6;0],parameters);
    model = build_multirotor_model(geometry,parameters.kappa, ...
        parameters.reaction_signs,parameters.actuator_bounds);
    set_options = struct('compute_force',true,'compute_moment',true, ...
        'compute_zero_moment_force',true, ...
        'equality_tolerance',solver.equality_tolerance, ...
        'bound_tolerance',solver.bound_tolerance, ...
        'vertex_tolerance',solver.vertex_tolerance, ...
        'hull_tolerance',solver.hull_tolerance);

    study_log('case_start',1,1,'Force, moment, and zero-moment force sets');
    timer = tic;
    sets = build_feasible_wrench_sets(model,set_options);
    force_extrema = wrench_set_extrema(model.A_f,model.actuator_bounds, ...
        {'F_x','F_y','F_z'});
    moment_extrema = wrench_set_extrema(model.A_tau,model.actuator_bounds, ...
        {'tau_x','tau_y','tau_z'});
    zero_moment_force_extrema_table = zero_moment_force_extrema( ...
        model.A_f,model.A_tau,model.actuator_bounds, ...
        {'F_x','F_y','F_z'},solver.equality_tolerance);

    force_plot_options = struct( ...
        'labels',[string(style.labels.force_set); ...
            string(style.labels.zero_moment_force_set)], ...
        'axis_labels',{{'$F_x$','$F_y$','$F_z$'}}, ...
        'colors',[style.colors.gray;style.colors.blue], ...
        'face_alpha',[style.alpha.surface_full; ...
            style.alpha.surface_restricted], ...
        'reference_point',parameters.hover_wrench(1:3), ...
        'reference_label',string(style.labels.hover_force));
    [force_figure,force_source_data] = plot_feasible_set( ...
        {sets.force,sets.zero_moment_force},force_plot_options);
    export_figure(force_figure,folder,'force_sets');
    write_figure_source_data(force_source_data,folder,'force_sets');
    close(force_figure);

    moment_plot_options = struct('labels',"", ...
        'axis_labels',{{'$\tau_x$','$\tau_y$','$\tau_z$'}}, ...
        'colors',style.colors.gray,'face_alpha',0.20);
    [moment_figure,moment_source_data] = plot_feasible_set( ...
        sets.moment,moment_plot_options);
    export_figure(moment_figure,folder,'moment_set');
    write_figure_source_data(moment_source_data,folder,'moment_set');
    close(moment_figure);

    save(fullfile(folder,'feasible_sets.mat'),'model','sets','force_extrema', ...
        'moment_extrema','zero_moment_force_extrema_table','set_options','-v7.3');
    writetable(force_extrema,fullfile(folder,'force_extrema.csv'));
    writetable(moment_extrema,fullfile(folder,'moment_extrema.csv'));
    writetable(zero_moment_force_extrema_table, ...
        fullfile(folder,'zero_moment_force_extrema.csv'));
    detail = sprintf('dimensions F=%d, T=%d, F0=%d', ...
        sets.force.affine_dimension,sets.moment.affine_dimension, ...
        sets.zero_moment_force.affine_dimension);
    logger = study_log('case_complete',logger,true,detail,toc(timer));
    study_log('stage_finish',logger);
    output = struct('model',model,'sets',sets,'force_extrema',force_extrema, ...
        'moment_extrema',moment_extrema, ...
        'zero_moment_force_extrema',zero_moment_force_extrema_table,'folder',folder);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
