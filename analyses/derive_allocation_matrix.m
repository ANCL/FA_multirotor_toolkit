function output = derive_allocation_matrix()
%DERIVE_ALLOCATION_MATRIX Export symbolic and matching numerical models.
%
% Symbolic Math Toolbox is required only for this command. The exported
% symbolic planar-shared matrix must agree elementwise with the canonical
% numerical allocation model at the reference substitution.

root = setup_project();
[parameters,~] = study_settings();
folder = ensure_folder(fullfile(root,'results','analyses','allocation_matrix'));
study_log('open',fullfile(folder,'run_log.txt'));
cleanup = onCleanup(@() study_log('close')); %#ok<NASGU>
logger = study_log('stage_start','Analysis', ...
    'Symbolic and numerical allocation matrices',1,0);
try
    study_log('case_start',1,1,'Six-rotor allocation model');
    timer = tic;

    generic_symbolic = generate_symbolic_allocation(parameters.n_rotors,false);
    planar_shared_symbolic = substitute_planar_shared_geometry( ...
        generic_symbolic,parameters.reaction_signs);
    zero_installation_symbolic = substitute_zero_installation_angles( ...
        generic_symbolic);

    % Numeric reference using the same planar-shared ordering and signs.
    reference_angles = [pi/6;0];
    reference_geometry = planar_shared_geometry(reference_angles,parameters);
    numeric_model = build_multirotor_model(reference_geometry,parameters.kappa, ...
        parameters.reaction_signs,parameters.actuator_bounds);

    symbolic_reference = double(subs(planar_shared_symbolic.A, ...
        [planar_shared_symbolic.shared_alpha; ...
         planar_shared_symbolic.shared_beta; ...
         planar_shared_symbolic.shared_kappa], ...
        [reference_angles;parameters.kappa]));
    consistency_error = max(abs(symbolic_reference-numeric_model.A),[],'all');
    consistency_tolerance = 1e-12;
    if consistency_error > consistency_tolerance
        error('fa:SymbolicNumericMismatch', ...
            ['Symbolic and numerical allocation matrices disagree: ' ...
             'maximum absolute error %.3g.'],consistency_error);
    end

    save(fullfile(folder,'allocation_models.mat'), ...
        'generic_symbolic','planar_shared_symbolic', ...
        'zero_installation_symbolic','reference_angles', ...
        'reference_geometry','numeric_model','symbolic_reference', ...
        'consistency_error','consistency_tolerance','-v7.3');
    export_symbolic_matrix_tex(planar_shared_symbolic.A, ...
        fullfile(folder,'planar_shared_allocation_matrix.tex'), ...
        'PlanarSharedAllocationMatrix');
    export_symbolic_matrix_tex(generic_symbolic.A, ...
        fullfile(folder,'generic_allocation_matrix.tex'), ...
        'GenericAllocationMatrix');
    writematrix(numeric_model.A,fullfile(folder,'numeric_allocation_matrix.csv'));
    writematrix(numeric_model.A_f,fullfile(folder,'numeric_force_matrix.csv'));
    writematrix(numeric_model.A_tau,fullfile(folder,'numeric_moment_matrix.csv'));

    detail = sprintf('symbolic/numeric agreement | max error %.3g', ...
        consistency_error);
    logger = study_log('case_complete',logger,true,detail,toc(timer));
    study_log('stage_finish',logger);
    output = struct( ...
        'generic_symbolic',generic_symbolic, ...
        'planar_shared_symbolic',planar_shared_symbolic, ...
        'zero_installation_symbolic',zero_installation_symbolic, ...
        'numeric_model',numeric_model, ...
        'consistency_error',consistency_error, ...
        'folder',folder);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
