function specifications = robustness_case_plan( ...
    designs,parameters,solver,batch_size)
%ROBUSTNESS_CASE_PLAN Deterministic robustness batch definitions.
types = {'position','direction','capacity','kappa'};
level_sets = {parameters.robustness.position_sigma, ...
    parameters.robustness.direction_sigma_rad, ...
    parameters.robustness.capacity_sigma,parameters.robustness.kappa_sigma};
template = struct('index',0,'case_name','','description','', ...
    'design_index',0,'type','','level_index',0,'level',NaN, ...
    'trial_numbers',[],'provenance',struct());
specifications = repmat(template,0,1);
index = 0;
for design_index = 1:numel(designs)
    for type_index = 1:numel(types)
        levels = level_sets{type_index};
        starts = 1:batch_size:parameters.robustness.trials_per_level;
        for level_index = 1:numel(levels)
            for batch_index = 1:numel(starts)
                index = index+1;
                first_trial = starts(batch_index);
                last_trial = min(parameters.robustness.trials_per_level, ...
                    first_trial+batch_size-1);
                case_name = sprintf( ...
                    '%s_%s_level_%02d_trials_%04d_%04d', ...
                    designs(design_index).name,types{type_index}, ...
                    level_index,first_trial,last_trial);
                description = sprintf( ...
                    '%s | %s | level %d/%d | batch %d/%d | trials %d-%d', ...
                    designs(design_index).name,types{type_index},level_index, ...
                    numel(levels),batch_index,numel(starts),first_trial,last_trial);
                specifications(end+1) = struct( ... %#ok<AGROW>
                    'index',index,'case_name',case_name, ...
                    'description',description,'design_index',design_index, ...
                    'type',types{type_index},'level_index',level_index, ...
                    'level',levels(level_index), ...
                    'trial_numbers',first_trial:last_trial,'provenance',struct());
            end
        end
    end
end
specifications = finalize_robustness_cases( ...
    specifications,designs,parameters,solver);
end
