function status = case_store_inventory(store,specifications)
%CASE_STORE_INVENTORY Cheap directory inventory of full and compact cases.
% One directory listing per store avoids thousands of individual filesystem
% probes on network-mounted result folders. The listing also supplies byte
% counts used for checkpoint-record reconciliation logging without extra I/O.
expected_names = string({specifications.case_name}).'+".mat";
full_listing = dir(fullfile(store.case_folder,'*.mat'));
record_listing = dir(fullfile(store.record_folder,'*.mat'));
full_names = string({full_listing.name}).';
record_names = string({record_listing.name}).';
[full_exists,full_location] = ismember(expected_names,full_names);
record_exists = ismember(expected_names,record_names);
full_bytes = zeros(numel(expected_names),1);
if any(full_exists)
    listing_bytes = [full_listing.bytes].';
    full_bytes(full_exists) = listing_bytes(full_location(full_exists));
end
orphan_records = record_exists & ~full_exists;
if any(orphan_records)
    first = find(orphan_records,1,'first');
    error('fa:OrphanCaseRecord', ...
        ['Compact record exists without its authoritative full checkpoint: %s\n' ...
         'Delete only that compact record, or restore the full checkpoint.'], ...
        case_record_path(store,specifications(first).case_name));
end
missing_record = full_exists & ~record_exists;
status = struct( ...
    'expected',numel(specifications), ...
    'full_exists',full_exists, ...
    'record_exists',record_exists, ...
    'full_bytes',full_bytes, ...
    'full_count',sum(full_exists), ...
    'record_count',sum(record_exists), ...
    'full_bytes_total',sum(full_bytes), ...
    'missing_full_count',sum(~full_exists), ...
    'missing_record_count',sum(missing_record), ...
    'missing_record_full_bytes',sum(full_bytes(missing_record)));
end
