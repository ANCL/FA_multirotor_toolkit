function digest = study_source_hash(study_name,root)
%STUDY_SOURCE_HASH Hash only the runner and helpers specific to one study.
if nargin < 2 || isempty(root)
    root = fileparts(fileparts(mfilename('fullpath')));
end
study_name = char(string(study_name));
switch study_name
    case 'design_comparison'
        relative = {'study/run_design_comparison.m', ...
            'internal/design_comparison_case_plan.m'};
    case 'task_evaluation'
        relative = {'study/run_task_evaluation.m'};
    case 'authority_effort'
        relative = {'study/run_pareto_analysis.m', ...
            'internal/authority_effort_threshold_plan.m', ...
            'internal/authority_effort_case_names.m'};
    case 'sensitivity'
        relative = {'study/run_sensitivity_analysis.m', ...
            'internal/sensitivity_case_plan.m', ...
            'internal/sensitivity_study_plan.m', ...
            'internal/task_emphasis_diagonal.m', ...
            'internal/sensitivity_case_id.m', ...
            'internal/numeric_case_token.m', ...
            'core/metrics/task_scale.m'};
    case 'robustness'
        relative = {'study/run_robustness_analysis.m', ...
            'internal/robustness_case_plan.m', ...
            'internal/execute_robustness_case.m'};
    case 'preflight'
        relative = {'run_preflight.m'};
    otherwise
        error('fa:UnknownNumericalStudy', ...
            'Unknown numerical study for provenance: %s',study_name);
end
files = cellfun(@(x) fullfile(root,strrep(x,'/',filesep)), ...
    relative,'UniformOutput',false);
digest = source_files_hash(files,root);
end
