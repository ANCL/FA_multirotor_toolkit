function report = parallel_environment_probe()
%PARALLEL_ENVIRONMENT_PROBE Verify that a worker sees the toolkit path.
task = getCurrentTask();
worker_id = NaN;
if ~isempty(task), worker_id = task.ID; end
report = struct( ...
    'worker_id',worker_id, ...
    'optimize_design_visible',exist('optimize_design','file') == 2, ...
    'evaluate_design_visible',exist('evaluate_design','file') == 2, ...
    'release',version('-release'));
if ~report.optimize_design_visible || ~report.evaluate_design_visible
    error('fa:WorkerPathIncomplete', ...
        'A parallel worker cannot see the toolkit numerical functions.');
end
end
