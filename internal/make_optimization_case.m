function specification = make_optimization_case(index,description,problem,parameters,seed,context)
%MAKE_OPTIMIZATION_CASE Create one independent optimization work item.
if nargin < 6 || isempty(context), context = struct(); end
specification = struct( ...
    'index',index, ...
    'case_name',char(string(problem.case_name)), ...
    'description',char(string(description)), ...
    'problem',problem, ...
    'parameters',parameters, ...
    'seed',seed, ...
    'context',context, ...
    'provenance',struct());
end
