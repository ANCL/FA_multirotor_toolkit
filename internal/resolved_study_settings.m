function resolved = resolved_study_settings(study_name,parameters,solver)
%RESOLVED_STUDY_SETTINGS Values actually used by one numerical study.
study_name = char(string(study_name));
base = resolved_case_parameters(parameters);
switch study_name
    case 'unrestricted_optimization'
        p1_solver = solver;
        p1_solver.ga.population_size = solver.rotorwise_ga_population_size;
        p1_solver.ga.max_generations = solver.rotorwise_ga_max_generations;
        p1_solver.ga.max_stall_generations = solver.rotorwise_ga_max_stall_generations;
        p1_solver.patternsearch.max_function_evaluations = ...
            solver.rotorwise_patternsearch_max_function_evaluations;
        resolved = struct('model',base, ...
            'objectives',{parameters.objectives}, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'rotorwise_ga_population_size',solver.rotorwise_ga_population_size, ...
            'rotorwise_ga_max_generations',solver.rotorwise_ga_max_generations, ...
            'rotorwise_patternsearch_max_function_evaluations', ...
                solver.rotorwise_patternsearch_max_function_evaluations, ...
            'optimization',resolved_optimization_solver(p1_solver));
    case 'p2_seeded_p1'
        p1_solver = solver;
        p1_solver.ga.population_size = solver.rotorwise_ga_population_size;
        p1_solver.ga.max_generations = solver.rotorwise_ga_max_generations;
        p1_solver.ga.max_stall_generations = solver.rotorwise_ga_max_stall_generations;
        p1_solver.patternsearch.max_function_evaluations = ...
            solver.rotorwise_patternsearch_max_function_evaluations;
        resolved = struct('model',base, ...
            'objectives',{{'r_F0','sigma_min','condition_number'}}, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'seed_source','optimized_spatial_c3_stage02', ...
            'initial_seed_policy','replace_first_deterministic_row', ...
            'optimization',resolved_optimization_solver(p1_solver));
    case 'parameterization_comparison'
        resolved = struct('model',base, ...
            'objectives',{parameters.objectives}, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    case {'authority_effort','authority_effort_p1'}
        resolved = struct('model',base, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'pareto_points',solver.pareto_points, ...
            'pareto_classification_tolerance', ...
                solver.pareto_classification_tolerance, ...
            'optimization',resolved_optimization_solver(solver));
    case 'sensitivity'
        resolved = struct('model',base, ...
            'sensitivity',parameters.sensitivity, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    case 'robustness'
        resolved = struct('model',base, ...
            'robustness',parameters.robustness, ...
            'master_seed',solver.master_seed, ...
            'evaluation',resolved_evaluation_solver(solver));
    case 'preflight'
        resolved = struct('model',base, ...
            'objectives',{parameters.objectives}, ...
            'sensitivity_length',parameters.sensitivity.characteristic_length_values(1), ...
            'sensitivity_kappa',parameters.sensitivity.kappa_values(end), ...
            'robustness_position_sigma',parameters.robustness.position_sigma(1), ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    otherwise
        error('fa:UnknownNumericalStudy', ...
            'Unknown numerical study for provenance: %s',study_name);
end
end
