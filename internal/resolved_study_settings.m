function resolved = resolved_study_settings(study_name,parameters,solver)
%RESOLVED_STUDY_SETTINGS Values actually used by one numerical study.
study_name = char(string(study_name));
base = resolved_case_parameters(parameters);
switch study_name
    case 'design_comparison'
        resolved = struct('model',base, ...
            'objectives',{parameters.objectives}, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    case 'task_evaluation'
        resolved = struct('model',base, ...
            'task_verification_increment',solver.task_verification_increment, ...
            'evaluation',resolved_evaluation_solver(solver));
    case 'authority_effort'
        resolved = struct('model',base, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'pareto_points',solver.pareto_points, ...
            'pareto_classification_tolerance', ...
                solver.pareto_classification_tolerance, ...
            'optimization',resolved_optimization_solver(solver));
    case 'sensitivity'
        resolved = struct('model',base, ...
            'sensitivity',parameters.sensitivity, ...
            'independent_runs',solver.independent_runs, ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    case 'robustness'
        resolved = struct('model',base, ...
            'robustness',parameters.robustness, ...
            'master_seed',solver.master_seed, ...
            'evaluation',resolved_evaluation_solver(solver));
    case 'preflight'
        resolved = struct('model',base, ...
            'objectives',{parameters.objectives}, ...
            'sensitivity_length',parameters.sensitivity.characteristic_length_values(1), ...
            'sensitivity_kappa',parameters.sensitivity.kappa_values(end), ...
            'robustness_position_sigma',parameters.robustness.position_sigma(1), ...
            'task_verification_increment',solver.task_verification_increment, ...
            'master_seed',solver.master_seed, ...
            'optimization',resolved_optimization_solver(solver));
    otherwise
        error('fa:UnknownNumericalStudy', ...
            'Unknown numerical study for provenance: %s',study_name);
end
end
