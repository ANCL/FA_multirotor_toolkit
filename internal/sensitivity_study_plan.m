function plan = sensitivity_study_plan(parameters,solver)
%SENSITIVITY_STUDY_PLAN Resolved physical sensitivity cases.
plan = struct( ...
    'actuator_capacity_values', ...
        parameters.sensitivity.actuator_capacity_values(:).', ...
    'kappa_values',parameters.sensitivity.kappa_values(:).', ...
    'characteristic_length_values', ...
        parameters.sensitivity.characteristic_length_values(:).', ...
    'hover_load_factor_values', ...
        parameters.sensitivity.hover_load_factor_values(:).', ...
    'include_bidirectional',parameters.sensitivity.include_bidirectional, ...
    'optimized_objectives',parameters.sensitivity.optimized_objectives, ...
    'normalization_cases',1:6, ...
    'independent_runs',solver.independent_runs, ...
    'master_seed',solver.master_seed, ...
    'selection_rule', ...
        'best valid objective value across normalization cases and repeats');
plan.matrix_metrics = parameters.sensitivity.matrix_metrics;
end
