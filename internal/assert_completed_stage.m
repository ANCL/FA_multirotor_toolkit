function provenance = assert_completed_stage( ...
    manifest_path,study_name,parameters,solver,upstream)
%ASSERT_COMPLETED_STAGE Verify completion and all canonical stage artifacts.
if nargin < 5 || isempty(upstream), upstream = struct(); end
provenance = assert_compatible_result( ...
    manifest_path,study_name,parameters,solver,upstream);
data = load(manifest_path,'manifest','provenance');
if ~isfield(data,'manifest') || ~isstruct(data.manifest) || ...
        ~isfield(data.manifest,'schema_version') || ...
        data.manifest.schema_version ~= 1 || ...
        ~isfield(data.manifest,'status') || ...
        ~strcmp(char(string(data.manifest.status)),'complete')
    error('fa:IncompleteStageManifest', ...
        'Stage manifest is missing or incomplete: %s',manifest_path);
end
if ~isfield(data.manifest,'study_name') || ...
        ~strcmp(char(string(data.manifest.study_name)),char(string(study_name)))
    error('fa:StageManifestStudy', ...
        'Stage manifest study name is inconsistent: %s',manifest_path);
end
if ~isfield(data.manifest,'study_hash') || ...
        ~strcmp(char(string(data.manifest.study_hash)), ...
            char(string(provenance.study_hash)))
    error('fa:StageManifestProvenance', ...
        'Stage manifest study hash is inconsistent: %s',manifest_path);
end
if ~isfield(data.manifest,'data_contract_hash') || ...
        ~strcmp(char(string(data.manifest.data_contract_hash)), ...
            char(string(provenance.data_contract_hash)))
    error('fa:StageManifestDataContract', ...
        'Stage manifest data-contract hash is inconsistent: %s',manifest_path);
end
if ~isfield(data.manifest,'artifacts') || isempty(data.manifest.artifacts)
    error('fa:EmptyStageManifest', ...
        'Completed stage manifest declares no artifacts: %s',manifest_path);
end
stage_folder = fileparts(manifest_path);
artifacts = string(data.manifest.artifacts(:));
for k = 1:numel(artifacts)
    path_in = fullfile(stage_folder,char(artifacts(k)));
    if ~isfile(path_in)
        error('fa:MissingStageArtifact', ...
            'Completed stage artifact is missing: %s',path_in);
    end
    artifact_data = load(path_in,'provenance');
    if ~isfield(artifact_data,'provenance') || ...
            ~isstruct(artifact_data.provenance) || ...
            ~isfield(artifact_data.provenance,'study_hash') || ...
            ~strcmp(char(string(artifact_data.provenance.study_hash)), ...
                char(string(provenance.study_hash)))
        error('fa:StageArtifactProvenance', ...
            'Stage artifact provenance is stale or inconsistent: %s',path_in);
    end
end
end
