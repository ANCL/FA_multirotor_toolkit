function validate_case_result_identity(result,specification,path_in)
%VALIDATE_CASE_RESULT_IDENTITY Verify one full or compact case payload.
if nargin < 3 || isempty(path_in), path_in = '<in-memory case>'; end
if ~isstruct(result) || ~isscalar(result) || ~isfield(result,'case_name') || ...
        ~strcmp(char(string(result.case_name)),char(string(specification.case_name)))
    error('fa:CaseResultIdentity', ...
        'Case payload identity is inconsistent for %s.',specification.case_name);
end
if ~isfield(result,'case_provenance') || ...
        ~isfield(result.case_provenance,'case_hash')
    error('fa:MissingCaseProvenance', ...
        'Case payload lacks provenance for %s.',specification.case_name);
end
assert_case_provenance_compatible( ...
    result.case_provenance,specification.provenance,path_in);

kind = char(string(specification.provenance.kind));
switch kind
    case 'optimization'
        required = {'objective_name','parameterization','normalization_case','seed'};
        for k = 1:numel(required)
            if ~isfield(result,required{k})
                error('fa:OptimizationCaseIdentity', ...
                    'Optimization payload lacks %s for %s.', ...
                    required{k},specification.case_name);
            end
        end
        if result.seed ~= specification.seed || ...
                ~strcmp(char(string(result.objective_name)), ...
                    char(string(specification.problem.objective))) || ...
                ~strcmp(char(string(result.parameterization)), ...
                    char(string(specification.problem.parameterization))) || ...
                result.normalization_case ~= specification.problem.normalization_case
            error('fa:OptimizationCaseIdentity', ...
                'Optimization checkpoint identity is inconsistent for %s.', ...
                specification.case_name);
        end
    case 'robustness'
        required = {'type','level','trial_numbers'};
        for k = 1:numel(required)
            if ~isfield(result,required{k})
                error('fa:RobustnessCaseIdentity', ...
                    'Robustness payload lacks %s for %s.', ...
                    required{k},specification.case_name);
            end
        end
        if ~strcmp(char(string(result.type)),char(string(specification.type))) || ...
                result.level ~= specification.level || ...
                ~isequal(result.trial_numbers,specification.trial_numbers)
            error('fa:RobustnessCaseIdentity', ...
                'Robustness checkpoint identity is inconsistent for %s.', ...
                specification.case_name);
        end
    otherwise
        error('fa:UnknownCaseProvenanceKind', ...
            'Unknown case provenance kind: %s',kind);
end
end
