function result = execute_robustness_case(specification,designs,parameters,solver)
%EXECUTE_ROBUSTNESS_CASE Evaluate one deterministic robustness batch.
timer = tic;
trial_numbers = specification.trial_numbers;
items = cell(numel(trial_numbers),1);
for k = 1:numel(trial_numbers)
    trial = evaluate_robustness_trial( ...
        designs(specification.design_index),specification.type, ...
        specification.level,trial_numbers(k),parameters,solver);
    if ~isempty(trial.internal_error_identifier)
        error(trial.internal_error_identifier,'%s',trial.failure_reason);
    end
    items{k} = trial;
end
trials = vertcat(items{:});
result = struct( ...
    'case_name',specification.case_name, ...
    'description',specification.description, ...
    'type',specification.type, ...
    'level',specification.level, ...
    'trial_numbers',trial_numbers, ...
    'trials',trials, ...
    'elapsed_seconds',toc(timer), ...
    'case_provenance',specification.provenance);
end
