function record = compact_optimization_result(result)
%COMPACT_OPTIMIZATION_RESULT Scientific record of one selected optimum.
% Full solver traces remain in the authoritative case checkpoint.
record = struct( ...
    'case_name',string(result.case_name), ...
    'objective_name',string(result.objective_name), ...
    'parameterization',string(result.parameterization), ...
    'normalization_case',result.normalization_case, ...
    'seed',result.seed, ...
    'design_variables',result.design_variables, ...
    'metrics',result.metrics, ...
    'objective_value',result.objective_value, ...
    'reported_objective_value',result.reported_objective_value, ...
    'constraint_violation',result.constraints.maximum_violation, ...
    'elapsed_seconds',result.elapsed_seconds, ...
    'valid',result.valid);
end
