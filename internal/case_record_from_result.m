function record = case_record_from_result(result)
%CASE_RECORD_FROM_RESULT Build the compact scientific twin of one checkpoint.
if ~isstruct(result) || ~isscalar(result) || ...
        ~isfield(result,'case_provenance') || ...
        ~isfield(result.case_provenance,'kind')
    error('fa:InvalidCaseResult','Cannot build a compact record from this result.');
end
switch char(string(result.case_provenance.kind))
    case 'optimization'
        record = compact_optimization_record(result);
    case 'robustness'
        record = compact_robustness_record(result);
    otherwise
        error('fa:UnknownCaseProvenanceKind', ...
            'Unknown case provenance kind: %s',result.case_provenance.kind);
end
record.record_schema_version = 1;
end

function record = compact_optimization_record(result)
metrics = compact_metrics(result);
context = struct();
if isfield(result,'context') && isstruct(result.context), context = result.context; end
record = struct( ...
    'case_name',char(string(result.case_name)), ...
    'objective_name',char(string(result.objective_name)), ...
    'parameterization',char(string(result.parameterization)), ...
    'normalization_case',result.normalization_case, ...
    'seed',result.seed, ...
    'design_variables',result.design_variables, ...
    'geometry',result.geometry, ...
    'metrics',metrics, ...
    'objective_value',scalar_field(result,'objective_value',NaN), ...
    'reported_objective_value',scalar_field(result,'reported_objective_value',NaN), ...
    'global_objective_value',scalar_field(result,'global_objective_value',NaN), ...
    'global_reported_objective_value', ...
        scalar_field(result,'global_reported_objective_value',NaN), ...
    'global_valid',logical_field(result,'global_valid',false), ...
    'global_constraint_violation', ...
        scalar_field(result,'global_constraint_violation',NaN), ...
    'selected_solver',char(string(text_field(result,'selected_solver',''))), ...
    'selected_constraint_violation',selected_violation(result), ...
    'global_exit_flag',scalar_field(result,'global_exit_flag',NaN), ...
    'exit_flag',scalar_field(result,'exit_flag',NaN), ...
    'global_generations',solver_output_field(result,'global_solver_output','generations'), ...
    'global_evaluation_count',global_evaluation_count(result), ...
    'global_termination_message', ...
        solver_output_message(result,'global_solver_output'), ...
    'selected_termination_message',solver_output_message(result,'solver_output'), ...
    'local_improvement',scalar_field(result,'local_improvement',NaN), ...
    'constraints',struct('maximum_violation',maximum_violation(result)), ...
    'evaluation_count',scalar_field(result,'evaluation_count',NaN), ...
    'elapsed_seconds',scalar_field(result,'elapsed_seconds',NaN), ...
    'failure_reason',char(string(text_field(result,'failure_reason',''))), ...
    'context',context, ...
    'valid',logical_field(result,'valid',false), ...
    'case_provenance',result.case_provenance);
end

function record = compact_robustness_record(result)
record = struct( ...
    'case_name',char(string(result.case_name)), ...
    'description',char(string(text_field(result,'description',''))), ...
    'type',char(string(result.type)), ...
    'level',result.level, ...
    'trial_numbers',result.trial_numbers, ...
    'trials',result.trials, ...
    'elapsed_seconds',scalar_field(result,'elapsed_seconds',NaN), ...
    'case_provenance',result.case_provenance);
end

function metrics = compact_metrics(result)
metrics = struct('r_F0',NaN,'sigma_min',NaN,'condition_number',NaN, ...
    'hover_effort',NaN,'q_star',NaN,'task_feasible',false,'valid',false);
if ~isfield(result,'metrics') || ~isstruct(result.metrics), return; end
names = {'r_F0','sigma_min','condition_number','hover_effort','q_star'};
for k = 1:numel(names)
    if isfield(result.metrics,names{k})
        metrics.(names{k}) = result.metrics.(names{k});
    end
end
if isfield(result.metrics,'task_feasible')
    metrics.task_feasible = logical(result.metrics.task_feasible);
end
if isfield(result.metrics,'valid')
    metrics.valid = logical(result.metrics.valid);
elseif isfield(result,'valid')
    metrics.valid = logical(result.valid);
end
end

function value = scalar_field(s,name,default_value)
value = default_value;
if isfield(s,name) && isnumeric(s.(name)) && isscalar(s.(name))
    value = s.(name);
end
end

function value = logical_field(s,name,default_value)
value = default_value;
if isfield(s,name) && isscalar(s.(name))
    value = logical(s.(name));
end
end

function value = text_field(s,name,default_value)
value = default_value;
if isfield(s,name) && ~isempty(s.(name)), value = s.(name); end
end

function value = maximum_violation(result)
value = NaN;
if isfield(result,'constraints') && isstruct(result.constraints) && ...
        isfield(result.constraints,'maximum_violation')
    value = result.constraints.maximum_violation;
elseif isfield(result,'selected_constraint_violation')
    value = result.selected_constraint_violation;
end
end

function value = selected_violation(result)
value = scalar_field(result,'selected_constraint_violation',NaN);
if ~isfinite(value), value = maximum_violation(result); end
end

function value = solver_output_field(result,field_name,value_name)
value = NaN;
if isfield(result,field_name) && isstruct(result.(field_name)) && ...
        isfield(result.(field_name),value_name) && ...
        isnumeric(result.(field_name).(value_name)) && ...
        isscalar(result.(field_name).(value_name))
    value = result.(field_name).(value_name);
end
end

function value = global_evaluation_count(result)
value = scalar_field(result,'global_evaluation_count',NaN);
if ~isfinite(value)
    value = solver_output_field(result,'global_solver_output','funccount');
end
end

function message = solver_output_message(result,field_name)
message = '';
if isfield(result,field_name) && isstruct(result.(field_name)) && ...
        isfield(result.(field_name),'message') && ~isempty(result.(field_name).message)
    message = char(string(result.(field_name).message));
end
end
