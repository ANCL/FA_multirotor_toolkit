cases(1) = make_baseline('task_emphasis', ...
    sensitivity_case_id('task_emphasis',rho_0),'rho',rho_0,rho_0, ...
    diag(parameters.task.Lambda),struct('rho',rho_0, ...
    'task_diagonal',diag(parameters.task.Lambda)), ...
    study.matrix_metrics);
cases(2) = make_baseline('actuator_capacity', ...
    sensitivity_case_id('actuator_capacity',1),'mu_max',1,NaN, ...
    diag(parameters.task.Lambda),struct('mu_max',1, ...
    'actuator_bounds',parameters.actuator_bounds), ...
    study.matrix_metrics);
cases(3) = make_baseline('reaction_moment', ...
    sensitivity_case_id('reaction_moment',parameters.kappa),'kappa', ...
    parameters.kappa,NaN,diag(parameters.task.Lambda), ...
    struct('kappa',parameters.kappa), ...
    study.matrix_metrics);
cases(4) = make_baseline('characteristic_length', ...
    sensitivity_case_id('characteristic_length',parameters.force_moment_length), ...
    'L',parameters.force_moment_length,NaN,diag(parameters.task.Lambda), ...
    struct('L',parameters.force_moment_length), ...
    study.matrix_metrics);
cases(5) = make_baseline('directionality','unidirectional', ...
    'actuator_bounds',0,NaN,diag(parameters.task.Lambda), ...
    struct('actuator_bounds',parameters.actuator_bounds), ...
    study.matrix_metrics);
cases(6) = make_baseline('hover_load', ...
    sensitivity_case_id('hover_load',1),'hover_load_factor',1,NaN, ...
    diag(parameters.task.Lambda),struct('hover_load_factor',1, ...
    'hover_wrench',parameters.hover_wrench), ...
    study.matrix_metrics);
