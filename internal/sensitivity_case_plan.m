function specifications = expand_optimization_groups( ...
    groups,parameters,solver,baseline_designs,index_offset)
base_seeds = initial_rotorwise_seeds(parameters,solver);
count = sum(arrayfun(@(x) numel(x.objectives),groups))*6*solver.independent_runs;
template_problem = make_design_problem('rotorwise','q_star',1,parameters);
template = make_optimization_case(1,'',template_problem,parameters,1,struct());
specifications = repmat(template,count,1);
solver_settings = resolved_optimization_solver(solver);
index = 0;
for group_index = 1:numel(groups)
    group = groups(group_index);
    for objective_index = 1:numel(group.objectives)
        objective = group.objectives{objective_index};
        baseline = baseline_designs(strcmp({baseline_designs.name},objective));
        if numel(baseline) ~= 1
            error('fa:MissingSensitivityBaseline', ...
                'Expected one selected baseline design for objective %s.',objective);
        end
        for normalization_case = 1:6
            for repeat = 1:solver.independent_runs
                index = index+1;
                case_name = sprintf('%s_%s_norm_%d_run_%d', ...
                    group.case_id,objective,normalization_case,repeat);
                description = sprintf( ...
                    '%s | %s | condition-specific optimum | normalization %d/6 | repeat %d/%d', ...
                    group.analysis,group.case_id,normalization_case,repeat, ...
                    solver.independent_runs);
                problem = make_design_problem( ...
                    'rotorwise',objective,normalization_case,group.parameters);
                problem.initial_designs = base_seeds{normalization_case};
                included_incumbent = ...
                    baseline.optimization_result.normalization_case == normalization_case;
                if included_incumbent
                    problem.initial_designs = [ ...
                        baseline.optimization_result.design_variables(:).'; ...
                        problem.initial_designs];
                end
                problem.case_name = case_name;
                seed = stable_seed(solver.master_seed,case_name);
                incumbent_information = struct( ...
                    'baseline_objective',objective, ...
                    'baseline_normalization_case', ...
                        baseline.optimization_result.normalization_case, ...
                    'included_in_initial_designs',included_incumbent);
                hash_inputs = struct( ...
                    'task_diagonal',group.task_diagonal, ...
                    'rho',group.rho, ...
                    'physical_value',group.physical_value, ...
                    'modified_parameters',group.modified_parameters, ...
                    'objective',objective, ...
                    'normalization_case',normalization_case, ...
                    'parameterization','rotorwise', ...
                    'repeat',repeat, ...
                    'deterministic_seed',seed, ...
                    'solver_settings',solver_settings, ...
                    'initial_designs',problem.initial_designs, ...
                    'incumbent_information',incumbent_information);
                context = struct( ...
                    'sensitivity_case',group.case_id, ...
                    'analysis',group.analysis, ...
                    'physical_parameter',group.physical_parameter, ...
                    'physical_value',group.physical_value, ...
                    'rho',group.rho, ...
                    'task_diagonal',group.task_diagonal, ...
                    'modified_parameters',group.modified_parameters, ...
                    'objective',objective, ...
                    'normalization_case',normalization_case, ...
                    'repeat',repeat, ...
                    'deterministic_seed',seed, ...
                    'solver_settings',solver_settings, ...
                    'incumbent_information',incumbent_information, ...
                    'hash_inputs',hash_inputs);
                specifications(index) = make_optimization_case( ...
                    index_offset+index,description,problem,group.parameters, ...
                    seed,context);
            end
        end
    end
end
specifications = finalize_optimization_cases(specifications,solver);
end

function compact = compact_provenance_plan(plan)
compact = struct();
compact.study = plan.study;
compact.fixed = compact_cases(plan.fixed_cases);
compact.baseline = compact_cases(plan.baseline_cases);
compact.optimized = provenance_plan(plan.specifications);
end

function output = compact_cases(cases)
template = struct('analysis','','case_id','','physical_parameter','', ...
    'physical_value',NaN,'rho',NaN,'task_diagonal',zeros(6,1), ...
    'modified_parameters',struct(),'objectives',{{}});
output = repmat(template,numel(cases),1);
for k = 1:numel(cases)
    output(k) = struct('analysis',cases(k).analysis, ...
        'case_id',cases(k).case_id, ...
        'physical_parameter',cases(k).physical_parameter, ...
        'physical_value',cases(k).physical_value, ...
        'rho',cases(k).rho, ...
        'task_diagonal',cases(k).task_diagonal, ...
        'modified_parameters',cases(k).modified_parameters, ...
        'objectives',{cases(k).objectives});
end
end

