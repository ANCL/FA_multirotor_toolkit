function plan = sensitivity_case_plan(parameters,solver,baseline_designs)
%SENSITIVITY_CASE_PLAN Resolve physical sensitivity cases and checkpoints.
% The baseline point of each family reuses the completed nominal selected
% geometry. Every changed physical condition expands to six normalization
% cases and the configured deterministic repeats.
if nargin < 3, baseline_designs = struct([]); end
plan = struct();
plan.study = sensitivity_study_plan(parameters,solver);
plan.fixed_cases = build_fixed_cases(parameters,plan.study);
plan.baseline_cases = build_baseline_cases(parameters,plan.study);
plan.optimization_groups = build_optimization_groups(parameters,plan.study);
if isempty(baseline_designs)
    plan.specifications = struct([]);
else
    fixed_count = sum(arrayfun(@(x) numel(x.objectives),plan.fixed_cases));
    plan.specifications = expand_optimization_groups( ...
        plan.optimization_groups,parameters,solver,baseline_designs,fixed_count);
end
plan.fixed_evaluation_count = sum(arrayfun( ...
    @(x) numel(x.objectives),plan.fixed_cases));
plan.baseline_result_count = sum(arrayfun( ...
    @(x) numel(x.objectives),plan.baseline_cases));
plan.optimization_group_count = sum(arrayfun( ...
    @(x) numel(x.objectives),plan.optimization_groups));
plan.optimization_case_count = numel(plan.specifications);
plan.expected_summary_rows = plan.fixed_evaluation_count;
plan.provenance = compact_provenance_plan(plan);
end

function cases = build_fixed_cases(parameters,study)
template = case_template(parameters);
cases = repmat(template,0,1);
for k = 1:numel(study.task_emphasis_values)
    rho = study.task_emphasis_values(k);
    diagonal = study.task_diagonals(:,k);
    p = parameters;
    p.task.Lambda = diag(diagonal);
    modified = struct('rho',rho,'task_diagonal',diagonal);
    cases(end+1) = make_case('task_emphasis', ... %#ok<AGROW>
        sensitivity_case_id('task_emphasis',rho),'rho',rho,rho, ...
        diagonal,modified,p,study.matrix_metrics);
end
for k = 1:numel(study.actuator_capacity_values)
    value = study.actuator_capacity_values(k);
    p = parameters;
    bounds = [zeros(parameters.n_rotors,1), ...
        value*ones(parameters.n_rotors,1)];
    p.actuator_bounds = bounds;
    modified = struct('mu_max',value,'actuator_bounds',bounds);
    cases(end+1) = make_case('actuator_capacity', ... %#ok<AGROW>
        sensitivity_case_id('actuator_capacity',value),'mu_max',value,NaN, ...
        diag(p.task.Lambda),modified,p, ...
        study.matrix_metrics);
end
for k = 1:numel(study.kappa_values)
    value = study.kappa_values(k);
    p = parameters;
    p.kappa = value;
    modified = struct('kappa',value);
    cases(end+1) = make_case('reaction_moment', ... %#ok<AGROW>
        sensitivity_case_id('reaction_moment',value),'kappa',value,NaN, ...
        diag(p.task.Lambda),modified,p, ...
        study.matrix_metrics);
end
for k = 1:numel(study.characteristic_length_values)
    value = study.characteristic_length_values(k);
    p = parameters;
    p.force_moment_length = value;
    modified = struct('L',value);
    cases(end+1) = make_case('characteristic_length', ... %#ok<AGROW>
        sensitivity_case_id('characteristic_length',value),'L',value,NaN, ...
        diag(p.task.Lambda),modified,p, ...
        study.matrix_metrics);
end
cases(end+1) = make_case('directionality','unidirectional', ... %#ok<AGROW>
    'actuator_bounds',0,NaN,diag(parameters.task.Lambda), ...
    struct('actuator_bounds',parameters.actuator_bounds),parameters, ...
    study.matrix_metrics);
if parameters.sensitivity.include_bidirectional
    p = parameters;
    bounds = [-ones(parameters.n_rotors,1),ones(parameters.n_rotors,1)];
    p.actuator_bounds = bounds;
    cases(end+1) = make_case('directionality','bidirectional', ... %#ok<AGROW>
        'actuator_bounds',1,NaN,diag(p.task.Lambda), ...
        struct('actuator_bounds',bounds),p, ...
        study.matrix_metrics);
end
for k = 1:numel(study.hover_load_factor_values)
    value = study.hover_load_factor_values(k);
    p = parameters;
    p.hover_wrench = value*parameters.hover_wrench;
    modified = struct('hover_load_factor',value, ...
        'hover_wrench',p.hover_wrench);
    cases(end+1) = make_case('hover_load', ... %#ok<AGROW>
        sensitivity_case_id('hover_load',value),'hover_load_factor', ...
        value,NaN,diag(p.task.Lambda),modified,p, ...
        study.matrix_metrics);
end
end

