function compare_provenance(actual,expected,label,path_in,fields)
%COMPARE_PROVENANCE Raise a precise component mismatch error.
if nargin < 5 || isempty(fields)
    fields = {'core_hash','source_hash','settings_hash','data_contract_hash', ...
        'plan_hash','upstream_hash'};
end
if ~isstruct(actual) || ~isfield(actual,'schema_version') || actual.schema_version ~= 2
    error('fa:UnsupportedProvenance', ...
        ['%s uses missing or unsupported provenance: %s\n' ...
         'Regenerate only this study-local file. Do not delete or move ' ...
         'results/current as a whole.'],label,path_in);
end
for k = 1:numel(fields)
    name = fields{k};
    if ~isfield(actual,name) || ~isfield(expected,name) || ...
            ~strcmp(char(string(actual.(name))),char(string(expected.(name))))
        error('fa:ProvenanceMismatch', ...
            ['%s is incompatible in component "%s": %s\n' ...
             'Delete or regenerate only this study-local file/folder; ' ...
             'results/current as a whole must remain untouched.'], ...
            label,name,path_in);
    end
end
end
