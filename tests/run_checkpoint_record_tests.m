function output = run_checkpoint_record_tests()
%RUN_CHECKPOINT_RECORD_TESTS Cheap regressions for full-checkpoint twins.
setup_project();
[parameters,solver] = study_settings();
folder = tempname;
mkdir(folder);
cleanup = onCleanup(@() remove_test_folder(folder)); %#ok<NASGU>
store = open_case_store(folder,'checkpoint_record_test');

specifications = design_comparison_case_plan('structured',parameters,solver);
specification = specifications(1);
result = fake_result(specification);
write_full_checkpoint_only(store,specification.case_name,result);

status = case_store_inventory(store,specification);
assert(status.full_count == 1 && status.record_count == 0);
runtime = struct('parallel_enabled',false);
[records,~,stats] = reconcile_case_records(specification,store,runtime);
assert(numel(records) == 1 && stats.records_built == 1);
assert(isfile(case_record_path(store,specification.case_name)));
assert(strcmp(records(1).case_provenance.case_hash, ...
    specification.provenance.case_hash));
assert(records(1).metrics.r_F0 == result.metrics.r_F0);
assert(~isfield(records(1),'global_solver_output'));

% New checkpoint saves create the compact twin immediately.
delete(case_record_path(store,specification.case_name));
record = case_store_save(store,specification.case_name,result);
assert(isfile(case_store_path(store,specification.case_name)));
assert(isfile(case_record_path(store,specification.case_name)));
assert(strcmp(record.case_provenance.case_hash,specification.provenance.case_hash));

output = struct('missing_twin_rebuilt',true, ...
    'new_checkpoint_writes_twin',true, ...
    'compact_payload_excludes_solver_trace',true);
fprintf('CHECKPOINT RECORD TESTS PASSED\n');
end

function result = fake_result(specification)
metrics = struct('r_F0',1.1,'sigma_min',0.2,'condition_number',4.0, ...
    'hover_effort',0.9,'valid',true);
geometry = struct('p',zeros(3,6),'u',repmat([0;0;-1],1,6),'spin',ones(6,1));
result = struct( ...
    'case_name',specification.case_name, ...
    'objective_name',specification.problem.objective, ...
    'parameterization',specification.problem.parameterization, ...
    'normalization_case',specification.problem.normalization_case, ...
    'seed',specification.seed, ...
    'design_variables',zeros(1,3), ...
    'geometry',geometry, ...
    'metrics',metrics, ...
    'objective_value',-1.1, ...
    'reported_objective_value',1.1, ...
    'global_objective_value',-1.0, ...
    'global_reported_objective_value',1.0, ...
    'global_valid',true, ...
    'global_constraint_violation',0, ...
    'selected_solver','test', ...
    'selected_constraint_violation',0, ...
    'global_exit_flag',1, ...
    'exit_flag',1, ...
    'global_solver_output',struct('generations',1,'funccount',2,'message','ok'), ...
    'solver_output',struct('message','ok'), ...
    'local_improvement',0.1, ...
    'constraints',struct('maximum_violation',0), ...
    'evaluation_count',3, ...
    'elapsed_seconds',0.01, ...
    'failure_reason','', ...
    'context',specification.context, ...
    'valid',true, ...
    'case_provenance',specification.provenance);
end

function write_full_checkpoint_only(store,case_name,result)
path_out = case_store_path(store,case_name);
saved_case_name = char(string(case_name)); %#ok<NASGU>
case_provenance = result.case_provenance; %#ok<NASGU>
case_result = result; %#ok<NASGU>
saved_at = datetime('now'); %#ok<NASGU>
save(path_out,'case_result','saved_case_name','case_provenance','saved_at','-v7');
end

function remove_test_folder(folder)
if isfolder(folder), rmdir(folder,'s'); end
end
