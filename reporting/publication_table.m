function T = publication_table(T)
%PUBLICATION_TABLE Convert internal identifiers to stable paper terminology.
if isempty(T), return; end

if ismember('parameterization',T.Properties.VariableNames)
    values = string(T.parameterization);
    values(values=="rotorwise") = "Rotor-wise";
    values(values=="spatial_c3") = "Spatial C3-symmetric";
    values(values=="planar_shared") = "Planar shared-angle";
    T.parameterization = values;
end
for variable = {'name','design_name','objective'}
    key = variable{1};
    if ismember(key,T.Properties.VariableNames)
        T.(key) = objective_text(string(T.(key)));
    end
end
for variable = {'analysis','case_name','sensitivity_case','perturbation_type'}
    key = variable{1};
    if ismember(key,T.Properties.VariableNames)
        T.(key) = identifier_text(string(T.(key)));
    end
end

old_names = string(T.Properties.VariableNames);
new_names = old_names;
exact_map = { ...
    'parameterization','Parameterization'; ...
    'name','Design'; ...
    'design_name','Design'; ...
    'objective','Objective'; ...
    'analysis','Analysis'; ...
    'case_name','Case'; ...
    'physical_parameter','PhysicalParameter'; ...
    'parameter_value','ParameterValue'; ...
    'rho','Rho'; ...
    'sensitivity_case','SensitivityCase'; ...
    'perturbation_type','Perturbation'; ...
    'geometry_role','GeometryRole'; ...
    'nominal_geometry','NominalGeometry'; ...
    'condition_specific_optimum','ConditionSpecificOptimum'; ...
    'task_feasible','TaskFeasible'; ...
    'task_feasibility','TaskFeasibility'; ...
    'minimum_separation','MinimumSeparation'; ...
    'minimum_hover_margin','MinimumHoverMargin'; ...
    'authority_threshold','AuthorityThreshold'; ...
    'normalization_case','NormalizationCase'; ...
    'threshold_index','ThresholdIndex'; ...
    'constraint_violation','ConstraintViolation'; ...
    'elapsed_seconds','ElapsedSeconds'; ...
    'total_trials','TotalTrials'; ...
    'force_authority_verified','ForceAuthorityVerified'; ...
    'q_star_verified','TaskScaleVerified'; ...
    'larger_scale_infeasible','LargerScaleInfeasible'; ...
    'limiting_actuator','LimitingActuator'; ...
    'limiting_bound','LimitingBound'; ...
    'attempted_independent_runs','AttemptedRuns'; ...
    'valid_independent_runs','ValidRuns'; ...
    'best_objective_value','BestObjectiveValue'; ...
    'median_objective_value','MedianObjectiveValue'; ...
    'worst_objective_value','WorstObjectiveValue'; ...
    'absolute_run_spread','AbsoluteRunSpread'; ...
    'relative_run_spread','RelativeRunSpread'; ...
    'valid','Valid'; ...
    'quantity','Quantity'; ...
    'value','Value'; ...
    'units','Units'; ...
    'rotor_wise','RotorWise'; ...
    'spatial_c3','SpatialC3'; ...
    'planar_shared','PlanarShared'; ...
    'design','Design'; ...
    'family','Family'; ...
    'metric','Metric'; ...
    'mu_max','ActuatorUpperBound'; ...
    'kappa','ReactionMomentRatio'; ...
    'L','CharacteristicLength'; ...
    'lambda_Fx','LambdaFx'; ...
    'lambda_Fy','LambdaFy'; ...
    'lambda_Fz','LambdaFz'; ...
    'lambda_Mx','LambdaMx'; ...
    'lambda_My','LambdaMy'; ...
    'lambda_Mz','LambdaMz'};
for index = 1:size(exact_map,1)
    new_names(old_names==exact_map{index,1}) = exact_map{index,2};
end
metric_map = { ...
    'condition_number','ConditionNumber'; ...
    'hover_effort','HoverEffort'; ...
    'sigma_min','MinimumSingularValue'; ...
    'q_star','TaskScale'; ...
    'r_F0','ForceAuthority'};
for index = 1:size(metric_map,1)
    new_names = replace(new_names,metric_map{index,1},metric_map{index,2});
end
new_names = replace(new_names,'_median','Median');
new_names = replace(new_names,'_p05','P05');
new_names = replace(new_names,'_p95','P95');
new_names = replace(new_names,'_minimum','Minimum');
new_names = replace(new_names,'_maximum','Maximum');
new_names = replace(new_names,'_finite_count','FiniteCount');
new_names = replace(new_names,'_lower_95','Lower95');
new_names = replace(new_names,'_upper_95','Upper95');
new_names = replace(new_names,'_','');
new_names = matlab.lang.makeUniqueStrings(matlab.lang.makeValidName(new_names));
T.Properties.VariableNames = cellstr(new_names);
end

function values = objective_text(values)
output = values;
output(endsWith(values,"r_F0")) = "Force-authority design";
output(endsWith(values,"sigma_min")) = "Weakest-gain design";
output(endsWith(values,"condition_number")) = "Isotropy design";
output(endsWith(values,"hover_effort")) = "Hover-effort design";
output(endsWith(values,"q_star")) = "Task-oriented design";
values = identifier_text(output);
end

function values = identifier_text(values)
output = values;
for index = 1:numel(values)
    token = char(values(index));
    switch token
        case 'task_emphasis'
            replacement = 'Task emphasis';
        case 'actuator_capacity'
            replacement = 'Actuator capacity';
        case 'reaction_moment'
            replacement = 'Reaction-moment ratio';
        case 'characteristic_length'
            replacement = 'Characteristic length';
        case 'directionality'
            replacement = 'Actuator directionality';
        case 'unidirectional'
            replacement = 'Unidirectional bounds';
        case 'bidirectional'
            replacement = 'Bidirectional bounds';
        case 'position'
            replacement = 'Rotor position';
        case 'direction'
            replacement = 'Thrust direction';
        case 'capacity'
            replacement = 'Actuator capacity';
        case 'kappa'
            replacement = 'Reaction-moment ratio';
        case 'rotorwise'
            replacement = 'P1';
        case 'spatial_c3'
            replacement = 'P2';
        case 'planar_shared'
            replacement = 'P3';
        otherwise
            replacement = physical_case_text(token);
    end
    output(index) = string(replacement);
end
values = output;
end

function text = physical_case_text(token)
if startsWith(token,'task_rho_')
    text = ['Task emphasis, rho = ' decode_token(extractAfter(token,'task_rho_'))];
elseif startsWith(token,'mu_max_')
    text = ['Actuator upper bound = ' decode_token(extractAfter(token,'mu_max_'))];
elseif startsWith(token,'kappa_')
    text = ['Reaction-moment ratio = ' decode_token(extractAfter(token,'kappa_'))];
elseif startsWith(token,'L_')
    text = ['L = ' decode_token(extractAfter(token,'L_'))];
else
    text = strrep(token,'_',' ');
end
end

function text = decode_token(token)
text = strrep(char(token),'p','.');
end
