function validate_all_reporting_results(root,parameters,solver)
%VALIDATE_ALL_REPORTING_RESULTS Check completed stage contracts before output.
folders = output_folders(root);
files = reporting_result_files(folders);
required = { ...
    files.design_manifest;files.objective_cross;files.rotorwise_designs; ...
    files.rotorwise_repeatability;files.rotorwise_optimization_runs; ...
    files.parameterization_comparison;files.all_designs; ...
    files.structured_repeatability;files.structured_optimization_runs; ...
    files.nested_domain_audit; ...
    files.pareto_manifest;files.pareto;files.pareto_all; ...
    files.pareto_repeatability;files.pareto_optimization_runs; ...
    files.sensitivity_manifest;files.nominal_sensitivity; ...
    files.condition_specific_sensitivity_summary; ...
    files.condition_specific_sensitivity_repeatability; ...
    files.condition_specific_sensitivity_runs; ...
    files.robustness_manifest;files.robustness;files.robustness_trials};
require_output_files(required,'Complete publication output generation');

design_provenance = assert_completed_stage( ...
    files.design_manifest,'design_comparison',parameters,solver);
assert_completed_stage(files.pareto_manifest,'authority_effort', ...
    parameters,solver,design_provenance);
assert_completed_stage(files.sensitivity_manifest,'sensitivity', ...
    parameters,solver,design_provenance);
assert_completed_stage(files.robustness_manifest,'robustness', ...
    parameters,solver,design_provenance);
end
