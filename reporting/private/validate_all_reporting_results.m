function validate_all_reporting_results(root,parameters,solver)
%VALIDATE_ALL_REPORTING_RESULTS Check every source before publication cleanup.
folders = output_folders(root);
files = reporting_result_files(folders);
required = { ...
    files.objective_cross;files.rotorwise_designs; ...
    files.rotorwise_repeatability;files.rotorwise_optimization_runs; ...
    files.task;files.task_raw;files.parameterization_comparison; ...
    files.all_designs;files.structured_repeatability; ...
    files.structured_optimization_runs;files.nested_domain_audit; ...
    files.pareto;files.pareto_all;files.pareto_raw; ...
    files.pareto_repeatability;files.pareto_optimization_runs; ...
    files.nominal_sensitivity;files.nominal_sensitivity_raw; ...
    files.condition_specific_sensitivity_raw; ...
    files.condition_specific_sensitivity_summary; ...
    files.condition_specific_sensitivity_repeatability; ...
    files.condition_specific_sensitivity_runs; ...
    files.robustness;files.robustness_raw};
require_output_files(required,'Complete publication output generation');

design_provenance = assert_compatible_result( ...
    files.rotorwise_designs,'design_comparison',parameters,solver);
assert_compatible_result(files.task_raw,'task_evaluation', ...
    parameters,solver,design_provenance);
assert_compatible_result(files.pareto_raw,'authority_effort', ...
    parameters,solver,design_provenance);
assert_compatible_result(files.nominal_sensitivity_raw,'sensitivity', ...
    parameters,solver,design_provenance);
assert_compatible_result(files.condition_specific_sensitivity_raw, ...
    'sensitivity',parameters,solver,design_provenance);
assert_compatible_result(files.robustness_raw,'robustness', ...
    parameters,solver,design_provenance);

end
