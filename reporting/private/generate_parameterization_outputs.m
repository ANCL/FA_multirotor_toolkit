function output = generate_parameterization_outputs()
%GENERATE_PARAMETERIZATION_OUTPUTS Study 2 reporting implementation.
context = create_output_context('parameterizations', ...
    'Study 2: Parameterization comparison', ...
    '02_parameterization_comparison','Outputs 02',30);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.parameterization_manifest; ...
        context.files.parameterization_comparison; ...
        context.files.all_designs; ...
        context.files.structured_repeatability; ...
        context.files.structured_optimization_runs; ...
        context.files.nested_domain_audit};
    require_output_files(required,context.title);
    p1_provenance = assert_completed_stage(context.files.design_manifest, ...
        'unrestricted_optimization',context.parameters,context.solver);
    assert_completed_stage(context.files.parameterization_manifest, ...
        'parameterization_comparison',context.parameters,context.solver,p1_provenance);

    comparison = load_result_table(context.files.parameterization_comparison);
    repeatability = load_result_table(context.files.structured_repeatability);
    optimization_runs = load_result_table( ...
        context.files.structured_optimization_runs);
    nested_audit = load_result_table(context.files.nested_domain_audit);
    validate_parameterization_outputs(comparison);
    design_data = load(context.files.all_designs,'selected');
    [geometry_summary,rotor_details] = ...
        parameterization_geometry_distance(design_data.selected,context.parameters);
    % Retain the planar P3 selected designs as a convenient derived MAT file.
    selected = design_data.selected(startsWith( ...
        string({design_data.selected.name}),"planar_shared_"));
    for k = 1:numel(selected)
        selected(k).name = char(erase(string(selected(k).name),'planar_shared_'));
    end
    assert(numel(selected)==numel(context.parameters.objectives));
    context.paths = reset_study_output_paths(context.paths);

    save(fullfile(context.paths.tables,'planar_shared_selected_designs.mat'), ...
        'selected','-v7');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: parameterization comparison', ...
        parameterization_summary_table(comparison),context.paths.tables, ...
        'parameterization_comparison');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: aligned configuration distances',geometry_summary, ...
        context.paths.tables,'configuration_geometry_distance');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: rotorwise geometry differences',rotor_details, ...
        context.paths.tables,'configuration_rotor_differences');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: parameterization repeatability',repeatability, ...
        context.paths.diagnostics,'parameterization_run_repeatability');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: parameterization optimization runs',optimization_runs, ...
        context.paths.diagnostics,'parameterization_optimization_runs');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: nested-domain audit',nested_audit, ...
        context.paths.diagnostics,'nested_domain_audit');

    % The same geometry and feasible-force-set renderers used by Stage 01.
    figure_data = parameterization_plot_data( ...
        design_data.selected,context.parameters,context.solver);
    figure_names = strings(0,1);
    for index = 1:numel(figure_data)
        item = figure_data(index);
        geometry_name = char("geometry_"+item.family+"_"+item.objective);
        geometry_options = struct( ...
            'figure_position',context.style.dimensions.column_short, ...
            'view',[55 26], ...
            'show_angles',false, ...
            'show_rotor_groups',ismember(item.family,["p2","p3"]));
        [logger,completed] = run_output_figure(logger,completed, ...
            ['figure: ' geometry_name], ...
            @() plot_multirotor_configuration(item.geometry,geometry_options), ...
            context.paths.figures,geometry_name);
        force_name = char("force_sets_"+item.family+"_"+item.objective);
        force_options = struct( ...
            'labels',[string(context.style.labels.force_set); ...
            string(context.style.labels.zero_moment_force_set)], ...
            'axis_labels',{{'$F_x$','$F_y$','$F_z$'}}, ...
            'colors',[context.style.colors.gray;context.style.colors.blue], ...
            'face_alpha',[context.style.alpha.surface_full; ...
            context.style.alpha.surface_restricted], ...
            'axis_limits',item.force_limits, ...
            'figure_position',context.style.dimensions.column_short, ...
            'view',[55 26], ...
            'reference_point',context.parameters.hover_wrench(1:3), ...
            'reference_label',context.style.labels.hover_force);
        [logger,completed] = run_output_figure(logger,completed, ...
            ['figure: ' force_name], ...
            @() plot_feasible_set( ...
            {item.sets.force,item.sets.zero_moment_force},force_options), ...
            context.paths.figures,force_name);
        figure_names(end+1:end+2,1) = ...
            [string(geometry_name);string(force_name)]; %#ok<AGROW>
    end

    expected = ["parameterization_comparison"; ...
        "configuration_geometry_distance";"configuration_rotor_differences"; ...
        "parameterization_run_repeatability"; ...
        "parameterization_optimization_runs";"nested_domain_audit"; ...
        figure_names];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
