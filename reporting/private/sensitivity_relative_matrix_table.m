function T = sensitivity_relative_matrix_table(matrix)
%SENSITIVITY_RELATIVE_MATRIX_TABLE Percentage-focused sensitivity matrix.
required = { ...
    'analysis','case_name','physical_parameter','parameter_value','rho', ...
    'objective','metric','baseline_design','baseline_metric_value', ...
    'nominal_geometry','nominal_metric_available','nominal_valid', ...
    'nominal_change_pct','condition_specific_optimum', ...
    'condition_specific_metric_available','condition_specific_valid', ...
    'condition_specific_change_pct','condition_specific_improvement', ...
    'reoptimization_improvement_pct','reoptimization_required', ...
    'condition_specific_source'};
if ~all(ismember(required,matrix.Properties.VariableNames))
    error('fa:IncompleteSensitivityRelativeMatrix', ...
        'The complete sensitivity matrix is missing relative-change columns.');
end
T = matrix(:,required);
end
