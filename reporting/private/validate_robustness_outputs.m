function validate_robustness_outputs(summary,parameters)
%VALIDATE_ROBUSTNESS_OUTPUTS Check the completed robustness summary.

required = {'design_name','perturbation_type','level','total_trials', ...
    'evaluation_validity','geometric_feasibility', ...
    'full_actuation_feasibility','hover_feasibility', ...
    'task_feasibility','q_star_median'};

if ~all(ismember(required,summary.Properties.VariableNames))
    error('fa:IncompleteRobustnessSummary', ...
        'The robustness summary is missing required columns.');
end

level_count = numel(parameters.robustness.position_sigma) + ...
    numel(parameters.robustness.direction_sigma_rad) + ...
    numel(parameters.robustness.capacity_sigma) + ...
    numel(parameters.robustness.kappa_sigma);

expected_rows = ...
    numel(parameters.robustness.design_objectives)*level_count;

if height(summary) ~= expected_rows
    error('fa:IncompleteRobustnessSummary', ...
        'Expected %d robustness rows, but found %d.', ...
        expected_rows,height(summary));
end

keys = string(summary.design_name)+"/"+ ...
    string(summary.perturbation_type)+"/"+ ...
    compose('%.12g',summary.level);

if numel(unique(keys)) ~= height(summary)
    error('fa:DuplicateRobustnessSummary', ...
        'Robustness summary rows must have unique identifiers.');
end

if any(summary.total_trials ~= parameters.robustness.trials_per_level)
    error('fa:IncompleteRobustnessSummary', ...
        'A robustness summary row has an unexpected trial count.');
end

probabilities = [summary.evaluation_validity; ...
    summary.geometric_feasibility; ...
    summary.full_actuation_feasibility; ...
    summary.hover_feasibility; ...
    summary.task_feasibility];

if any(~isfinite(probabilities)) || ...
        any(probabilities < 0) || any(probabilities > 1)
    error('fa:InvalidRobustnessSummary', ...
        'Robustness feasibility proportions must lie in [0,1].');
end
end