function validate_robustness_outputs(path_in)
%VALIDATE_ROBUSTNESS_OUTPUTS Check trial count and unique identifiers.
data = load(path_in,'all_trials','expected_trials');
if ~isfield(data,'expected_trials') || ...
        numel(data.all_trials) ~= data.expected_trials
    error('fa:IncompleteRobustnessTrials', ...
        'Robustness trial count is incomplete.');
end
keys = strings(numel(data.all_trials),1);
for index = 1:numel(data.all_trials)
    keys(index) = sprintf('%s|%s|%.12g|%d', ...
        data.all_trials(index).design_name, ...
        data.all_trials(index).perturbation_type, ...
        data.all_trials(index).level, ...
        data.all_trials(index).trial_number);
end
if numel(unique(keys)) ~= data.expected_trials
    error('fa:DuplicateRobustnessTrials', ...
        'Robustness identifiers are not unique.');
end
end
