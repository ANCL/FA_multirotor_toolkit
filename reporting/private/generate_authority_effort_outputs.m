function output = generate_authority_effort_outputs()
%GENERATE_AUTHORITY_EFFORT_OUTPUTS Study 3 reporting implementation.
context = create_output_context('authority_effort', ...
    'Study 3: Authority-effort trade-off', ...
    '03_authority_effort_tradeoff','Outputs 03',4);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.design_manifest;context.files.parameterization_manifest;context.files.pareto_manifest; ...
        context.files.spatial_c3_designs;context.files.pareto;context.files.pareto_all; ...
        context.files.pareto_repeatability; ...
        context.files.pareto_optimization_runs};
    require_output_files(required,context.title);
    p1_provenance = assert_completed_stage(context.files.design_manifest, ...
        'unrestricted_optimization',context.parameters,context.solver);
    design_provenance = assert_completed_stage( ...
        context.files.parameterization_manifest,'parameterization_comparison', ...
        context.parameters,context.solver,p1_provenance);
    assert_completed_stage(context.files.pareto_manifest, ...
        'authority_effort',context.parameters,context.solver,design_provenance);

    summary = load_result_table(context.files.pareto);
    all_runs = load_result_table(context.files.pareto_all);
    repeatability = load_result_table(context.files.pareto_repeatability);
    optimization_runs = load_result_table(context.files.pareto_optimization_runs);
    validate_pareto_outputs(summary,context.solver);
    context.paths = reset_study_output_paths(context.paths);

    [logger,completed] = run_output_table(logger,completed, ...
        'table: authority-effort values',authority_effort_table(summary), ...
        context.paths.tables,'authority_effort_values');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: Pareto repeatability',repeatability, ...
        context.paths.diagnostics,'pareto_run_repeatability');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: Pareto optimization runs',optimization_runs, ...
        context.paths.diagnostics,'pareto_optimization_runs');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: authority-effort Pareto front and feasible runs', ...
        @() plot_pareto_runs(all_runs,summary), ...
        context.paths.figures, ...
        'authority_effort_tradeoff');

    expected = ["authority_effort_values"; ...
        "pareto_run_repeatability"; ...
        "pareto_optimization_runs"; ...
        "authority_effort_tradeoff"];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
