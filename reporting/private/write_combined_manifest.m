function write_combined_manifest(publication,parameters,solver,output)
%WRITE_COMBINED_MANIFEST Write the all-study reporting manifest.
manifest.study_id = parameters.study_id;
manifest.created_at = char(datetime('now', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
manifest.matlab_version = version;
manifest.matlab_release = version('-release');
manifest.numerical_core_hash = numerical_core_hash();
manifest.provenance_schema = 2;
manifest.presentation_revision = 'study_organized_outputs_v2';
manifest.study_folders = struct( ...
    'objective_designs',output.objective_designs.root, ...
    'parameterizations',output.parameterizations.root, ...
    'authority_effort',output.authority_effort.root, ...
    'sensitivity',output.sensitivity.root, ...
    'robustness',output.robustness.root);
manifest.completed_outputs = struct( ...
    'objective_designs',output.objective_designs.completed_outputs, ...
    'parameterizations',output.parameterizations.completed_outputs, ...
    'authority_effort',output.authority_effort.completed_outputs, ...
    'sensitivity',output.sensitivity.completed_outputs, ...
    'robustness',output.robustness.completed_outputs);
manifest.source_files = reporting_source_manifest(fileparts(fileparts(publication)));
save(fullfile(publication,'study_manifest.mat'),'manifest');
write_json_file(fullfile(publication,'study_manifest.json'),manifest);
end
