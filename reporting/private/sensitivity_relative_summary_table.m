function T = sensitivity_relative_summary_table(matrix)
%SENSITIVITY_RELATIVE_SUMMARY_TABLE Percentage extrema for each matrix cell.
keys = unique(string(matrix.analysis)+"|"+string(matrix.objective),'stable');
rows = repmat(relative_summary_template(),numel(keys),1);

for index = 1:numel(keys)
    selected = (string(matrix.analysis)+"|"+string(matrix.objective))==keys(index);
    family = matrix(selected,:);
    if isempty(family)
        error('fa:MissingSensitivityRelativeSummary', ...
            'No rows were found for sensitivity cell %s.',keys(index));
    end

    parameter = reported_parameter(family);
    baseline_rows = string(family.condition_specific_source)=="baseline";
    if sum(baseline_rows) ~= 1
        error('fa:MissingSensitivityBaseline', ...
            'Expected one baseline row for sensitivity cell %s.',keys(index));
    end
    baseline_index = find(baseline_rows,1);

    [nominal_minimum,nominal_min_index] = ...
        finite_extreme(family.nominal_change_pct,'min',false);
    [nominal_maximum,nominal_max_index] = ...
        finite_extreme(family.nominal_change_pct,'max',false);
    [nominal_max_abs,nominal_abs_index] = ...
        finite_extreme(family.nominal_change_pct,'max',true);

    [condition_minimum,condition_min_index] = ...
        finite_extreme(family.condition_specific_change_pct,'min',false);
    [condition_maximum,condition_max_index] = ...
        finite_extreme(family.condition_specific_change_pct,'max',false);
    [condition_max_abs,condition_abs_index] = ...
        finite_extreme(family.condition_specific_change_pct,'max',true);

    [maximum_reoptimization,maximum_reoptimization_index] = ...
        finite_extreme(family.reoptimization_improvement_pct,'max',false);

    rows(index) = struct( ...
        'analysis',string(family.analysis(1)), ...
        'objective',string(family.objective(1)), ...
        'physical_parameter',string(family.physical_parameter(1)), ...
        'number_of_points',height(family), ...
        'nominal_available_points',sum(family.nominal_metric_available), ...
        'nominal_valid_points',sum(family.nominal_valid), ...
        'condition_specific_available_points', ...
            sum(family.condition_specific_metric_available), ...
        'condition_specific_valid_points',sum(family.condition_specific_valid), ...
        'comparable_points',sum(family.nominal_valid & family.condition_specific_valid), ...
        'baseline_parameter_value',parameter(baseline_index), ...
        'baseline_metric_value',family.baseline_metric_value(baseline_index), ...
        'nominal_change_min_pct',nominal_minimum, ...
        'parameter_at_nominal_change_min',indexed_parameter(parameter,nominal_min_index), ...
        'nominal_change_max_pct',nominal_maximum, ...
        'parameter_at_nominal_change_max',indexed_parameter(parameter,nominal_max_index), ...
        'nominal_max_abs_change_pct',nominal_max_abs, ...
        'parameter_at_nominal_max_abs_change',indexed_parameter(parameter,nominal_abs_index), ...
        'condition_specific_change_min_pct',condition_minimum, ...
        'parameter_at_condition_specific_change_min', ...
            indexed_parameter(parameter,condition_min_index), ...
        'condition_specific_change_max_pct',condition_maximum, ...
        'parameter_at_condition_specific_change_max', ...
            indexed_parameter(parameter,condition_max_index), ...
        'condition_specific_max_abs_change_pct',condition_max_abs, ...
        'parameter_at_condition_specific_max_abs_change', ...
            indexed_parameter(parameter,condition_abs_index), ...
        'maximum_reoptimization_improvement_pct',maximum_reoptimization, ...
        'parameter_at_maximum_reoptimization_improvement', ...
            indexed_parameter(parameter,maximum_reoptimization_index));
end

T = struct2table(rows);
end

function parameter = reported_parameter(family)
parameter = family.parameter_value;
parameter = parameter(:);
end

function [value,index] = finite_extreme(values,mode,use_absolute)
finite_rows = find(isfinite(values));
if isempty(finite_rows)
    value = NaN;
    index = NaN;
    return;
end
finite_values = values(finite_rows);
comparison = finite_values;
if use_absolute
    comparison = abs(comparison);
end
switch mode
    case 'min'
        [selected_value,local_index] = min(comparison);
    case 'max'
        [selected_value,local_index] = max(comparison);
    otherwise
        error('fa:UnknownSummaryExtrema','Unknown extrema mode: %s.',mode);
end
index = finite_rows(local_index);
if use_absolute
    value = selected_value;
else
    value = finite_values(local_index);
end
end

function value = indexed_parameter(parameter,index)
if isnan(index)
    value = NaN;
else
    value = parameter(index);
end
end

function row = relative_summary_template()
row = struct( ...
    'analysis',"",'objective',"",'physical_parameter',"", ...
    'number_of_points',0,'nominal_available_points',0, ...
    'nominal_valid_points',0,'condition_specific_available_points',0, ...
    'condition_specific_valid_points',0,'comparable_points',0, ...
    'baseline_parameter_value',NaN, ...
    'baseline_metric_value',NaN, ...
    'nominal_change_min_pct',NaN, ...
    'parameter_at_nominal_change_min',NaN, ...
    'nominal_change_max_pct',NaN, ...
    'parameter_at_nominal_change_max',NaN, ...
    'nominal_max_abs_change_pct',NaN, ...
    'parameter_at_nominal_max_abs_change',NaN, ...
    'condition_specific_change_min_pct',NaN, ...
    'parameter_at_condition_specific_change_min',NaN, ...
    'condition_specific_change_max_pct',NaN, ...
    'parameter_at_condition_specific_change_max',NaN, ...
    'condition_specific_max_abs_change_pct',NaN, ...
    'parameter_at_condition_specific_max_abs_change',NaN, ...
    'maximum_reoptimization_improvement_pct',NaN, ...
    'parameter_at_maximum_reoptimization_improvement',NaN);
end
