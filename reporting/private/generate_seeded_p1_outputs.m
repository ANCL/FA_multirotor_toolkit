function output = generate_seeded_p1_outputs()
%GENERATE_SEEDED_P1_OUTPUTS Two tables, no plots or new optimization.
context = create_output_context('p2_seeded_p1', ...
    'Study 6: P2-seeded P1 numerical check','06_p2_seeded_p1','Outputs 06',2);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.p2_seeded_p1_manifest; ...
        context.files.p2_seeded_p1_comparison; ...
        context.files.p2_seeded_p1_designs; ...
        context.files.spatial_c3_designs};
    require_output_files(required,context.title);
    p1_provenance = assert_completed_stage(context.files.design_manifest, ...
        'unrestricted_optimization',context.parameters,context.solver);
    p2_provenance = assert_completed_stage(context.files.parameterization_manifest, ...
        'parameterization_comparison',context.parameters,context.solver,p1_provenance);
    assert_completed_stage(context.files.p2_seeded_p1_manifest, ...
        'p2_seeded_p1',context.parameters,context.solver,p2_provenance);
    comparison = load_result_table(context.files.p2_seeded_p1_comparison);
    p1_data = load(context.files.p2_seeded_p1_designs,'selected');
    p2_data = load(context.files.spatial_c3_designs,'selected');
    distances = seeded_p1_configuration_distance( ...
        p2_data.selected,p1_data.selected,context.parameters);
    context.paths = reset_study_output_paths(context.paths);
    [logger,completed] = run_output_table(logger,completed, ...
        'table: Stage 06 objective differences',comparison, ...
        context.paths.tables,'seeded_vs_baselines');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: Stage 06 configuration distances',distances, ...
        context.paths.tables,'seeded_configuration_distance');
    require_completed_outputs(completed, ...
        ["seeded_vs_baselines";"seeded_configuration_distance"],context.title);
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME); rethrow(ME);
end
end
