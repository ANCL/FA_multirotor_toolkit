function T = sensitivity_summary_table(nominal_results,condition_results)
%SENSITIVITY_SUMMARY_TABLE Natural and objective-form sensitivity values.
rows = repmat(struct('analysis',"",'case_name',"", ...
    'physical_parameter',"",'parameter_value',NaN,'rho',NaN, ...
    'objective',"",'metric',"",'nominal_geometry',NaN, ...
    'condition_specific_optimum',NaN,'nominal_objective_value',NaN, ...
    'condition_specific_objective_value',NaN, ...
    'condition_specific_improvement',NaN, ...
    'relative_improvement_pct',NaN),height(nominal_results),1);
for index = 1:height(nominal_results)
    analysis = string(nominal_results.analysis(index));
    case_name = string(nominal_results.case_name(index));
    objective = string(nominal_results.objective(index));
    metric = objective;
    metric_values = nominal_results.(char(metric));
    nominal_value = metric_values(index);
    condition_value = condition_specific_sensitivity_value( ...
        condition_results,case_name,objective,char(metric));
    [nominal_objective,condition_objective,improvement] = ...
        objective_values(nominal_value,condition_value,metric);
    relative_improvement = 100*improvement/max(abs(nominal_value),eps);
    rows(index) = struct('analysis',analysis,'case_name',case_name, ...
        'physical_parameter',string(nominal_results.physical_parameter(index)), ...
        'parameter_value',nominal_results.parameter_value(index), ...
        'rho',nominal_results.rho(index),'objective',objective,'metric',metric, ...
        'nominal_geometry',nominal_value, ...
        'condition_specific_optimum',condition_value, ...
        'nominal_objective_value',nominal_objective, ...
        'condition_specific_objective_value',condition_objective, ...
        'condition_specific_improvement',improvement, ...
        'relative_improvement_pct',relative_improvement);
end
T = struct2table(rows);
end

function [nominal_objective,condition_objective,improvement] = ...
    objective_values(nominal_value,condition_value,metric)
if any(string(metric)==["q_star","sigma_min"])
    nominal_objective = -nominal_value;
    condition_objective = -condition_value;
    improvement = condition_value-nominal_value;
elseif string(metric)=="condition_number"
    nominal_objective = nominal_value;
    condition_objective = condition_value;
    improvement = nominal_value-condition_value;
else
    error('fa:UnknownSensitivityMetric', ...
        'Unknown sensitivity metric: %s.',metric);
end
end
