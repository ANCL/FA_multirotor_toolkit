function T = sensitivity_summary_table(nominal_results,condition_results,solver)
%SENSITIVITY_SUMMARY_TABLE Complete parameter-metric sensitivity matrix.
rows = repmat(struct('analysis',"",'case_name',"", ...
    'physical_parameter',"",'parameter_value',NaN, ...
    'objective',"",'metric',"",'baseline_design',"", ...
    'baseline_metric_value',NaN, ...
    'nominal_geometry',NaN,'nominal_metric_available',false, ...
    'nominal_valid',false,'nominal_change_pct',NaN, ...
    'condition_specific_optimum',NaN, ...
    'condition_specific_metric_available',false,'condition_specific_valid',false, ...
    'condition_specific_change_pct',NaN, ...
    'nominal_objective_value',NaN, ...
    'condition_specific_objective_value',NaN, ...
    'condition_specific_improvement',NaN, ...
    'reoptimization_improvement_pct',NaN, ...
    'relative_improvement_pct',NaN, ...
    'reoptimization_required',false, ...
    'condition_specific_source',""),height(nominal_results),1);

required_nominal = {'valid','design_name'};
required_condition = {'valid','source'};
if ~all(ismember(required_nominal,nominal_results.Properties.VariableNames)) || ...
        ~all(ismember(required_condition,condition_results.Properties.VariableNames))
    error('fa:IncompleteSensitivityValidity', ...
        'Sensitivity stage data are missing validity/source fields required for reporting.');
end

for index = 1:height(nominal_results)
    analysis = string(nominal_results.analysis(index));
    case_name = string(nominal_results.case_name(index));
    objective = string(nominal_results.objective(index));
    metric = objective;

    nominal_raw = nominal_results.(char(metric));
    nominal_valid = logical(nominal_results.valid(index));
    nominal_metric_available = isfinite(nominal_raw(index));
    nominal_value = reported_metric_value( ...
        nominal_raw(index),nominal_metric_available);

    [condition_raw,source,condition_valid] = ...
        condition_specific_sensitivity_value( ...
            condition_results,case_name,objective,char(metric));
    condition_metric_available = isfinite(condition_raw);
    condition_value = reported_metric_value( ...
        condition_raw,condition_metric_available);

    comparable = nominal_valid && condition_valid && ...
        nominal_metric_available && condition_metric_available;
    [nominal_objective,condition_objective,improvement] = ...
        objective_values(nominal_value,condition_value,metric,comparable);
    reoptimization_improvement = relative_improvement( ...
        nominal_value,improvement);
    [physical_parameter,parameter_value] = reported_parameter( ...
        analysis,case_name,nominal_results.physical_parameter(index), ...
        nominal_results.parameter_value(index));

    rows(index) = struct( ...
        'analysis',analysis, ...
        'case_name',case_name, ...
        'physical_parameter',physical_parameter, ...
        'parameter_value',parameter_value, ...
        'objective',objective, ...
        'metric',metric, ...
        'baseline_design',string(nominal_results.design_name(index)), ...
        'baseline_metric_value',NaN, ...
        'nominal_geometry',nominal_value, ...
        'nominal_metric_available',nominal_metric_available, ...
        'nominal_valid',nominal_valid, ...
        'nominal_change_pct',NaN, ...
        'condition_specific_optimum',condition_value, ...
        'condition_specific_metric_available',condition_metric_available, ...
        'condition_specific_valid',condition_valid, ...
        'condition_specific_change_pct',NaN, ...
        'nominal_objective_value',nominal_objective, ...
        'condition_specific_objective_value',condition_objective, ...
        'condition_specific_improvement',improvement, ...
        'reoptimization_improvement_pct',reoptimization_improvement, ...
        'relative_improvement_pct',reoptimization_improvement, ...
        'reoptimization_required',source=="checkpoint", ...
        'condition_specific_source',source);
end

T = struct2table(rows);
T = add_baseline_relative_changes(T,solver);
end

function value = reported_metric_value(raw_value,is_available)
if is_available
    value = raw_value;
else
    value = NaN;
end
end

function value = relative_improvement(nominal_value,improvement)
if isfinite(nominal_value) && isfinite(improvement)
    value = 100*improvement/max(abs(nominal_value),eps);
else
    value = NaN;
end
end

function T = add_baseline_relative_changes(T,solver)
% Percentage changes use the physical metric rather than a sign-adjusted
% optimization ordinate. Unavailable metric values remain missing.
keys = string(T.analysis)+"|"+string(T.objective);
unique_keys = unique(keys,'stable');

for key_index = 1:numel(unique_keys)
    selected = keys==unique_keys(key_index);
    baseline_rows = selected & string(T.condition_specific_source)=="baseline";
    if sum(baseline_rows) ~= 1
        error('fa:MissingSensitivityBaseline', ...
            'Expected one baseline row for sensitivity cell %s.', ...
            unique_keys(key_index));
    end

    baseline_index = find(baseline_rows,1);
    if ~T.nominal_valid(baseline_index) || ...
            ~T.condition_specific_valid(baseline_index)
        error('fa:InvalidSensitivityBaseline', ...
            'The baseline condition must be scientifically valid for %s.', ...
            unique_keys(key_index));
    end
    baseline_value = T.nominal_geometry(baseline_index);
    if ~isfinite(baseline_value) || abs(baseline_value) <= solver.equality_tolerance
        error('fa:UndefinedSensitivityPercentage', ...
            'The baseline metric is unsuitable for percentage reporting for %s.', ...
            unique_keys(key_index));
    end
    denominator = abs(baseline_value);

    T.baseline_metric_value(selected) = baseline_value;

    nominal_rows = selected & T.nominal_metric_available & ...
        isfinite(T.nominal_geometry);
    T.nominal_change_pct(nominal_rows) = ...
        100*(T.nominal_geometry(nominal_rows)-baseline_value)/denominator;

    condition_rows = selected & T.condition_specific_metric_available & ...
        isfinite(T.condition_specific_optimum);
    T.condition_specific_change_pct(condition_rows) = ...
        100*(T.condition_specific_optimum(condition_rows)-baseline_value)/denominator;

    % The exact baseline is the reference condition by definition.
    T.nominal_change_pct(baseline_index) = 0;
    T.condition_specific_change_pct(baseline_index) = 0;
    T.reoptimization_improvement_pct(baseline_index) = 0;
    T.relative_improvement_pct(baseline_index) = 0;
end
end

function [nominal_objective,condition_objective,improvement] = ...
    objective_values(nominal_value,condition_value,metric,comparable)
if ~comparable || ~isfinite(nominal_value) || ~isfinite(condition_value)
    nominal_objective = NaN;
    condition_objective = NaN;
    improvement = NaN;
    return;
end
if any(string(metric)==["r_F0","sigma_min"])
    nominal_objective = -nominal_value;
    condition_objective = -condition_value;
    improvement = condition_value-nominal_value;
elseif any(string(metric)==["condition_number","hover_effort"])
    nominal_objective = nominal_value;
    condition_objective = condition_value;
    improvement = nominal_value-condition_value;
else
    error('fa:UnknownSensitivityMetric', ...
        'Unknown sensitivity metric: %s.',metric);
end
end

function [parameter,value] = reported_parameter( ...
    analysis,case_name,stored_parameter,stored_value)
if analysis=="directionality"
    parameter = "mu_min";
    switch case_name
        case "unidirectional"
            value = 0;
        case "bidirectional"
            value = -1;
        otherwise
            error('fa:UnknownDirectionalityCase', ...
                'Unknown directionality case: %s.',case_name);
    end
else
    parameter = string(stored_parameter);
    value = stored_value;
end
end
