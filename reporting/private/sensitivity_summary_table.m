function T = sensitivity_summary_table(nominal_results,condition_results)
%SENSITIVITY_SUMMARY_TABLE Natural metrics for all 27 sensitivity rows.
rows = repmat(struct('analysis',"",'case_name',"", ...
    'physical_parameter',"",'parameter_value',NaN,'rho',NaN, ...
    'objective',"",'metric',"",'nominal_geometry',NaN, ...
    'condition_specific_optimum',NaN),height(nominal_results),1);
for index = 1:height(nominal_results)
    analysis = string(nominal_results.analysis(index));
    case_name = string(nominal_results.case_name(index));
    objective = string(nominal_results.objective(index));
    metric = objective;
    metric_values = nominal_results.(char(metric));
    nominal_value = metric_values(index);
    condition_value = condition_specific_sensitivity_value( ...
        condition_results,case_name,objective,char(metric));
    rows(index) = struct('analysis',analysis,'case_name',case_name, ...
        'physical_parameter',string(nominal_results.physical_parameter(index)), ...
        'parameter_value',nominal_results.parameter_value(index), ...
        'rho',nominal_results.rho(index),'objective',objective,'metric',metric, ...
        'nominal_geometry',nominal_value, ...
        'condition_specific_optimum',condition_value);
end
T = struct2table(rows);
end
