function output = generate_robustness_outputs()
%GENERATE_ROBUSTNESS_OUTPUTS Study 5 reporting implementation.
context = create_output_context('robustness', ...
    'Study 5: Implementation robustness', ...
    '05_implementation_robustness','Outputs 05',3);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.design_manifest;context.files.robustness_manifest; ...
        context.files.rotorwise_designs;context.files.robustness; ...
        context.files.robustness_trials};
    require_output_files(required,context.title);
    design_provenance = assert_completed_stage( ...
        context.files.design_manifest,'design_comparison', ...
        context.parameters,context.solver);
    assert_completed_stage(context.files.robustness_manifest, ...
        'robustness',context.parameters,context.solver,design_provenance);

    robustness = load_result_table(context.files.robustness);
    robustness_trials = load_result_table(context.files.robustness_trials);
    validate_robustness_outputs(robustness,context.parameters);
    context.paths = reset_study_output_paths(context.paths);
    [logger,completed] = run_output_table(logger,completed, ...
        'table: robustness full summary',robustness,context.paths.tables, ...
        'robustness_full_summary');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: robustness trials',robustness_trials, ...
        context.paths.diagnostics,'robustness_trials');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: robustness summary', ...
        @() plot_robustness_summary(robustness),context.paths.figures, ...
        'robustness_summary');
    expected = ["robustness_full_summary";"robustness_trials"; ...
        "robustness_summary"];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
