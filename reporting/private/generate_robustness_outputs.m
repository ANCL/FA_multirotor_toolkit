function output = generate_robustness_outputs()
%GENERATE_ROBUSTNESS_OUTPUTS Study 5 reporting implementation.
context = create_output_context('robustness', ...
    'Study 5: Implementation robustness', ...
    '05_implementation_robustness','Outputs 05',5);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.rotorwise_designs; ...
        context.files.robustness;context.files.robustness_raw};
    require_output_files(required,context.title);
    design_provenance = assert_compatible_result( ...
        context.files.rotorwise_designs,'design_comparison', ...
        context.parameters,context.solver);
    assert_compatible_result(context.files.robustness_raw, ...
        'robustness',context.parameters,context.solver,design_provenance);
    validate_robustness_outputs(context.files.robustness_raw);

    robustness = load_result_table(context.files.robustness);
    context.paths = reset_study_output_paths(context.paths);
    [logger,completed] = run_output_table(logger,completed, ...
        'table: robustness full summary',robustness,context.paths.tables, ...
        'robustness_full_summary');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: robustness task-scale summary', ...
        @() plot_robustness_summary(robustness),context.paths.figures, ...
        'robustness_task_scale_summary');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: robustness task-feasibility summary', ...
        @() plot_robustness_task_rate(robustness),context.paths.figures, ...
        'robustness_task_feasibility_summary');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: actuator-capacity robustness trend', ...
        @() plot_robustness_qstar(robustness,'capacity'), ...
        context.paths.figures,'robustness_capacity_task_scale');
    [logger,completed] = run_output_figure(logger,completed, ...
        'figure: thrust-direction robustness trend', ...
        @() plot_robustness_qstar(robustness,'direction'), ...
        context.paths.figures,'robustness_direction_task_scale');

    expected = ["robustness_full_summary"; ...
        "robustness_task_scale_summary"; ...
        "robustness_task_feasibility_summary"; ...
        "robustness_capacity_task_scale"; ...
        "robustness_direction_task_scale"];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
