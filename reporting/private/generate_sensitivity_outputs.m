function output = generate_sensitivity_outputs()
%GENERATE_SENSITIVITY_OUTPUTS Study 4 physical-sensitivity reporting.
context = create_output_context('sensitivity', ...
    'Study 4: Assumption sensitivity', ...
    '04_assumption_sensitivity','Outputs 04',10);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.rotorwise_designs; ...
        context.files.nominal_sensitivity; ...
        context.files.nominal_sensitivity_raw; ...
        context.files.condition_specific_sensitivity_raw; ...
        context.files.condition_specific_sensitivity_summary; ...
        context.files.condition_specific_sensitivity_repeatability; ...
        context.files.condition_specific_sensitivity_runs};
    require_output_files(required,context.title);
    design_provenance = assert_compatible_result( ...
        context.files.rotorwise_designs,'design_comparison', ...
        context.parameters,context.solver);
    assert_compatible_result(context.files.nominal_sensitivity_raw, ...
        'sensitivity',context.parameters,context.solver,design_provenance);
    assert_compatible_result(context.files.condition_specific_sensitivity_raw, ...
        'sensitivity',context.parameters,context.solver,design_provenance);

    nominal_results = load_result_table(context.files.nominal_sensitivity);
    condition_results = load_result_table( ...
        context.files.condition_specific_sensitivity_summary);
    repeatability = load_result_table( ...
        context.files.condition_specific_sensitivity_repeatability);
    optimization_runs = load_result_table( ...
        context.files.condition_specific_sensitivity_runs);

    all_cases = sensitivity_summary_table(nominal_results,condition_results);
    validate_sensitivity_outputs(all_cases,context.parameters,context.solver);
    curve_summary = sensitivity_curve_summary_table( ...
        all_cases,context.parameters);

    task_data = add_negated_plot_metric(sensitivity_plot_table( ...
        nominal_results,condition_results,'task_emphasis', ...
        'q_star','q_star','rho','rho'),'q_star','minus_q');
    capacity_data = add_negated_plot_metric(sensitivity_plot_table( ...
        nominal_results,condition_results,'actuator_capacity', ...
        'q_star','q_star','parameter_value','mu_max'), ...
        'q_star','minus_q');
    reaction_data = add_negated_plot_metric(sensitivity_plot_table( ...
        nominal_results,condition_results,'reaction_moment', ...
        'q_star','q_star','parameter_value','kappa'), ...
        'q_star','minus_q');
    weakest_gain_data = add_negated_plot_metric(sensitivity_plot_table( ...
        nominal_results,condition_results,'characteristic_length', ...
        'sigma_min','sigma_min','parameter_value','L'), ...
        'sigma_min','minus_sigma_min');
    isotropy_data = sensitivity_plot_table( ...
        nominal_results,condition_results,'characteristic_length', ...
        'condition_number','condition_number','parameter_value','L');
    context.paths = reset_study_output_paths(context.paths);

    [logger,completed] = run_output_figure_with_data(logger,completed, ...
        'figure: task emphasis',@() build_task_figure(task_data), ...
        context.paths.figures,'sensitivity_task_emphasis');
    [logger,completed] = run_output_figure_with_data(logger,completed, ...
        'figure: actuator capacity',@() build_capacity_figure(capacity_data), ...
        context.paths.figures,'sensitivity_actuator_capacity');
    [logger,completed] = run_output_figure_with_data(logger,completed, ...
        'figure: reaction moment',@() build_reaction_figure(reaction_data), ...
        context.paths.figures,'sensitivity_reaction_moment');
    [logger,completed] = run_output_figure_with_data(logger,completed, ...
        'figure: characteristic-length weakest gain', ...
        @() build_weakest_gain_figure(weakest_gain_data), ...
        context.paths.figures,'sensitivity_length_weakest_gain');
    [logger,completed] = run_output_figure_with_data(logger,completed, ...
        'figure: characteristic-length isotropy', ...
        @() build_isotropy_figure(isotropy_data), ...
        context.paths.figures,'sensitivity_length_isotropy');

    [logger,completed] = run_output_table(logger,completed, ...
        'table: sensitivity curve summary',curve_summary, ...
        context.paths.tables,'sensitivity_curve_summary');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: directionality sensitivity', ...
        sensitivity_directionality_table(nominal_results,condition_results), ...
        context.paths.tables,'sensitivity_directionality');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: all sensitivity cases', ...
        all_cases,context.paths.diagnostics,'sensitivity_all_cases');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: optimization repeatability',repeatability, ...
        context.paths.diagnostics,'condition_specific_repeatability');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: optimization runs',optimization_runs, ...
        context.paths.diagnostics,'condition_specific_design_runs');

    expected = ["sensitivity_task_emphasis"; ...
        "sensitivity_actuator_capacity"; ...
        "sensitivity_reaction_moment"; ...
        "sensitivity_length_weakest_gain"; ...
        "sensitivity_length_isotropy"; ...
        "sensitivity_curve_summary"; ...
        "sensitivity_directionality"; ...
        "sensitivity_all_cases"; ...
        "condition_specific_repeatability"; ...
        "condition_specific_design_runs"];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end

function [fig,data] = build_task_figure(data)
options = struct( ...
    'x_label','$\rho$', ...
    'y_label','$-q^\star$', ...
    'show_task_feasibility',true, ...
    'x_ticks',[0,0.25,0.5,0.75,1], ...
    'x_tick_labels',{{'0','0.25','0.5','0.75','1'}});

fig = plot_sensitivity_comparison(data,'rho','minus_q',options);
end

function [fig,data] = build_capacity_figure(data)
options = struct('x_label','$\mu_{\max}$', ...
    'y_label','$-q^\star$','show_task_feasibility',true, ...
    'x_ticks',[0.8,0.9,1.0,1.1,1.2], ...
    'x_tick_labels',{{'0.8','0.9','1','1.1','1.2'}});
fig = plot_sensitivity_comparison(data,'mu_max','minus_q',options);
end

function [fig,data] = build_reaction_figure(data)
options = struct('x_label','$\kappa$', ...
    'y_label','$-q^\star$','show_task_feasibility',true, ...
    'show_legend',true,'legend_location','north', ...
    'legend_headroom',0.34, ...
    'x_ticks',[0,0.015,0.03,0.045,0.06], ...
    'x_tick_labels',{{'0','0.015','0.03','0.045','0.06'}});
fig = plot_sensitivity_comparison(data,'kappa','minus_q',options);
end

function [fig,data] = build_weakest_gain_figure(data)
options = length_options('$-\sigma_{\min}(\bar A)$');
fig = plot_sensitivity_comparison(data,'L','minus_sigma_min',options);
end

function [fig,data] = build_isotropy_figure(data)
options = length_options('$C(\bar A)$');
fig = plot_sensitivity_comparison(data,'L','condition_number',options);
end

function options = length_options(y_label)
options = struct('x_label','$L$', ...
    'y_label',y_label,'log_x',true, ...
    'x_ticks',[0.5,1/sqrt(2),1,sqrt(2),2], ...
    'x_tick_labels',{{'0.5','$1/\sqrt{2}$','1','$\sqrt{2}$','2'}});
end

function data = add_negated_plot_metric(data,source_name,target_name)
data.(target_name) = -data.(source_name);
end

function labels = task_tick_labels(values)
labels = arrayfun(@task_tick_label,values,'UniformOutput',false);
end

function label = task_tick_label(value)
tolerance = 100*eps(max(1,abs(value)));
if abs(value) <= tolerance
    label = '0';
elseif abs(value-1) <= tolerance
    label = '1';
else
    label = sprintf('%.3f',value);
end
end
