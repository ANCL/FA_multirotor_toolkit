function [fig,data] = build_sensitivity_matrix_figure(data,specification)

options = struct( ...
    'x_label',specification.x_label, ...
    'y_label',specification.y_label, ...
    'log_x',specification.log_x, ...
    'show_task_feasibility',specification.show_task_feasibility, ...
    'show_zero_reference',false, ...
    'x_ticks',specification.x_ticks, ...
    'x_tick_labels',{specification.x_tick_labels}, ...
    'show_legend',specification.show_legend, ...
    'legend_location',specification.legend_location, ...
    'legend_headroom',0);

fig = plot_sensitivity_comparison( ...
    data, ...
    specification.parameter_name, ...
    specification.plot_metric, ...
    options);

end


