function output = generate_sensitivity_outputs()
%GENERATE_SENSITIVITY_OUTPUTS Study 4 complete sensitivity-matrix reporting.

specifications = sensitivity_plot_specifications();
table_output_count = 7;
context = create_output_context('sensitivity', ...
    'Study 4: Assumption sensitivity', ...
    '04_assumption_sensitivity','Outputs 04', ...
    2*numel(specifications)+table_output_count);

logger = context.logger;
completed = strings(0,1);

try
    required = {context.files.design_manifest;context.files.sensitivity_manifest; ...
        context.files.rotorwise_designs; ...
        context.files.nominal_sensitivity; ...
        context.files.condition_specific_sensitivity_summary; ...
        context.files.condition_specific_sensitivity_repeatability; ...
        context.files.condition_specific_sensitivity_runs};

    require_output_files(required,context.title);

    design_provenance = assert_completed_stage( ...
        context.files.design_manifest,'design_comparison', ...
        context.parameters,context.solver);

    assert_completed_stage( ...
        context.files.sensitivity_manifest, ...
        'sensitivity',context.parameters,context.solver,design_provenance);

    nominal_results = load_result_table( ...
        context.files.nominal_sensitivity);

    condition_results = load_result_table( ...
        context.files.condition_specific_sensitivity_summary);

    repeatability = load_result_table( ...
        context.files.condition_specific_sensitivity_repeatability);

    optimization_runs = load_result_table( ...
        context.files.condition_specific_sensitivity_runs);

    matrix = sensitivity_summary_table( ...
        nominal_results,condition_results,context.solver);

    validate_sensitivity_outputs( ...
        matrix,context.parameters,context.solver);
    log_sensitivity_matrix_status(matrix);

    relative_matrix = sensitivity_relative_matrix_table(matrix);
    curve_summary = sensitivity_curve_summary_table( ...
        matrix,context.parameters);
    relative_curve_summary = sensitivity_relative_summary_table(matrix);

    context.paths = reset_study_output_paths(context.paths);

    % Raw-value figures preserve the established objective/minimization
    % plotting convention. Only the first raw plot carries the legend.
    for index = 1:numel(specifications)
        specification = specifications(index);
        data = sensitivity_matrix_plot_data(matrix,specification);
        show_legend = index == 1;
        description = sprintf('figure: %s / %s', ...
            specification.analysis,specification.metric);
        [logger,completed] = run_output_figure_with_data( ...
            logger,completed,description, ...
            @() build_sensitivity_matrix_figure( ...
                data,specification,show_legend), ...
            context.paths.figures,specification.output_name);
    end

    % Percentage-change figures use the physical metric relative to the
    % corresponding metric's exact nominal-condition P1 baseline. The first
    % relative plot carries the same legend so this alternate set is directly
    % usable on its own without changing legend terminology.
    for index = 1:numel(specifications)
        specification = specifications(index);
        data = sensitivity_relative_plot_table( ...
            matrix,specification.analysis,specification.metric, ...
            specification.parameter_source,specification.parameter_name);
        show_legend = index == 1;
        description = sprintf('relative figure: %s / %s', ...
            specification.analysis,specification.metric);
        [logger,completed] = run_output_figure_with_data( ...
            logger,completed,description, ...
            @() build_sensitivity_relative_figure( ...
                data,specification,show_legend), ...
            context.paths.figures,[specification.output_name '_relative']);
    end

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: complete sensitivity matrix', ...
        matrix, ...
        context.paths.tables, ...
        'sensitivity_matrix');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: relative sensitivity matrix', ...
        relative_matrix, ...
        context.paths.tables, ...
        'sensitivity_matrix_relative');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: sensitivity curve summary', ...
        curve_summary, ...
        context.paths.tables, ...
        'sensitivity_curve_summary');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: relative sensitivity curve summary', ...
        relative_curve_summary, ...
        context.paths.tables, ...
        'sensitivity_curve_summary_relative');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: directionality sensitivity', ...
        sensitivity_directionality_table(matrix), ...
        context.paths.tables, ...
        'sensitivity_directionality');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'diagnostic: optimization repeatability', ...
        repeatability, ...
        context.paths.diagnostics, ...
        'condition_specific_repeatability');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'diagnostic: optimization runs', ...
        optimization_runs, ...
        context.paths.diagnostics, ...
        'condition_specific_design_runs');

    relative_names = string({specifications.output_name}).'+"_relative";
    expected = [ ...
        string({specifications.output_name}).'; ...
        relative_names; ...
        "sensitivity_matrix"; ...
        "sensitivity_matrix_relative"; ...
        "sensitivity_curve_summary"; ...
        "sensitivity_curve_summary_relative"; ...
        "sensitivity_directionality"; ...
        "condition_specific_repeatability"; ...
        "condition_specific_design_runs"];

    require_completed_outputs( ...
        completed,expected,context.title);

    context.logger = logger;
    output = finish_output_study( ...
        context,logger,completed);

catch ME
    study_log('error',ME);
    rethrow(ME);
end

end

function specifications = sensitivity_plot_specifications()
% One independent plot for each parameter-metric cell. The ordering here is
% also the presentation ordering used to decide which single plot in each
% reporting family has a legend.
families = [ ...
    family_spec('task_emphasis','rho','rho','$\rho$', ...
        false,[0,0.25,0.5,0.75,1], ...
        {'0','0.25','0.5','0.75','1'}); ...
    family_spec('actuator_capacity','parameter_value','mu_max','$\mu_{\max}$', ...
        false,[0.8,0.9,1.0,1.1,1.2], ...
        {'0.8','0.9','1','1.1','1.2'}); ...
    family_spec('hover_load','parameter_value','zeta_h','$\zeta_h$', ...
        false,[0.8,0.9,1.0,1.1,1.2], ...
        {'0.8','0.9','1','1.1','1.2'}); ...
    family_spec('reaction_moment','parameter_value','kappa','$\kappa$', ...
        false,[0,0.015,0.03,0.045,0.06], ...
        {'0','0.015','0.03','0.045','0.06'}); ...
    family_spec('directionality','mu_min','mu_min','$\mu_{\min}$', ...
        false,[-1,0],{'-1','0'}); ...
    family_spec('characteristic_length','parameter_value','L','$L$', ...
        true,[0.5,1/sqrt(2),1,sqrt(2),2], ...
        {'0.5','$1/\sqrt{2}$','1','$\sqrt{2}$','2'})];

metrics = [ ...
    metric_spec('q_star','minus_q','$-q^\star$', ...
        '$\Delta q^\star$ (\%)',true); ...
    metric_spec('r_F0','minus_r_F0','$-r_{\mathcal F_0}$', ...
        '$\Delta r_{\mathcal F_0}$ (\%)',false); ...
    metric_spec('sigma_min','minus_sigma_min', ...
        '$-\sigma_{\min}(\bar A)$', ...
        '$\Delta \sigma_{\min}(\bar A)$ (\%)',false); ...
    metric_spec('condition_number','condition_number', ...
        '$C(\bar A)$','$\Delta C(\bar A)$ (\%)',false); ...
    metric_spec('hover_effort','hover_effort','$J_{\mathrm h}$', ...
        '$\Delta J_{\mathrm h}$ (\%)',false)];

specifications = repmat(plot_spec_template(),numel(families)*numel(metrics),1);
index = 0;
for family_index = 1:numel(families)
    for metric_index = 1:numel(metrics)
        index = index+1;
        family = families(family_index);
        metric = metrics(metric_index);
        specifications(index) = struct( ...
            'analysis',family.analysis, ...
            'parameter_source',family.parameter_source, ...
            'parameter_name',family.parameter_name, ...
            'x_label',family.x_label, ...
            'log_x',family.log_x, ...
            'x_ticks',family.x_ticks, ...
            'x_tick_labels',{family.x_tick_labels}, ...
            'metric',metric.metric, ...
            'plot_metric',metric.plot_metric, ...
            'y_label',metric.y_label, ...
            'relative_y_label',metric.relative_y_label, ...
            'show_task_feasibility',metric.show_task_feasibility, ...
            'output_name',sprintf('sensitivity_%s_%s', ...
                family.analysis,metric.metric));
    end
end
end

function item = family_spec(analysis,parameter_source,parameter_name, ...
    x_label,log_x,x_ticks,x_tick_labels)
item = struct('analysis',analysis, ...
    'parameter_source',parameter_source, ...
    'parameter_name',parameter_name, ...
    'x_label',x_label,'log_x',log_x, ...
    'x_ticks',x_ticks,'x_tick_labels',{x_tick_labels});
end

function item = metric_spec( ...
    metric,plot_metric,y_label,relative_y_label,task_feasibility)
item = struct('metric',metric,'plot_metric',plot_metric, ...
    'y_label',y_label,'relative_y_label',relative_y_label, ...
    'show_task_feasibility',task_feasibility);
end

function item = plot_spec_template()
item = struct('analysis','','parameter_source','','parameter_name','', ...
    'x_label','','log_x',false,'x_ticks',[], ...
    'x_tick_labels',{{}},'metric','','plot_metric','','y_label','', ...
    'relative_y_label','','show_task_feasibility',false,'output_name','');
end

function data = sensitivity_matrix_plot_data(matrix,specification)
data = sensitivity_plot_table( ...
    matrix, ...
    specification.analysis, ...
    specification.metric,specification.metric, ...
    specification.parameter_source,specification.parameter_name);

if strcmp(specification.metric,'q_star')
    data.minus_q = -data.q_star;
elseif strcmp(specification.metric,'r_F0')
    data.minus_r_F0 = -data.r_F0;
elseif strcmp(specification.metric,'sigma_min')
    data.minus_sigma_min = -data.sigma_min;
end
end

function [fig,data] = build_sensitivity_matrix_figure( ...
    data,specification,show_legend)
options = struct( ...
    'x_label',specification.x_label, ...
    'y_label',specification.y_label, ...
    'log_x',specification.log_x, ...
    'show_task_feasibility',specification.show_task_feasibility, ...
    'show_zero_reference',false, ...
    'x_ticks',specification.x_ticks, ...
    'x_tick_labels',{specification.x_tick_labels}, ...
    'show_legend',show_legend, ...
    'legend_location','northeast', ...
    'legend_headroom',0);
fig = plot_sensitivity_comparison( ...
    data,specification.parameter_name,specification.plot_metric,options);
end

function [fig,data] = build_sensitivity_relative_figure( ...
    data,specification,show_legend)
options = struct( ...
    'x_label',specification.x_label, ...
    'y_label',specification.relative_y_label, ...
    'log_x',specification.log_x, ...
    'show_task_feasibility',false, ...
    'show_zero_reference',true, ...
    'x_ticks',specification.x_ticks, ...
    'x_tick_labels',{specification.x_tick_labels}, ...
    'show_legend',show_legend, ...
    'legend_location','northeast', ...
    'legend_headroom',0);
fig = plot_sensitivity_comparison( ...
    data,specification.parameter_name,'relative_change_pct',options);
end

function log_sensitivity_matrix_status(matrix)
row_count = height(matrix);
nominal_available = sum(matrix.nominal_metric_available);
nominal_valid = sum(matrix.nominal_valid);
condition_available = sum(matrix.condition_specific_metric_available);
condition_valid = sum(matrix.condition_specific_valid);
study_log('line', ...
    ['Sensitivity matrix: %d rows | nominal metrics %d/%d available, ' ...
     '%d/%d valid | condition-specific metrics %d/%d available, %d/%d valid.'], ...
    row_count,nominal_available,row_count,nominal_valid,row_count, ...
    condition_available,row_count,condition_valid,row_count);
if nominal_available < row_count || condition_available < row_count
    study_log('line', ...
        ['Unavailable scientific metric values are retained in the tables ' ...
         'as NaN and appear as gaps in figures.']);
end
end
