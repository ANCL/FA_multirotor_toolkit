    options);

end


function log_sensitivity_matrix_status(matrix)

row_count = height(matrix);

nominal_available = sum(matrix.nominal_metric_available);
nominal_valid = sum(matrix.nominal_valid);

condition_available = ...
    sum(matrix.condition_specific_metric_available);
condition_valid = ...
    sum(matrix.condition_specific_valid);

study_log('line', ...
    ['Sensitivity matrix: %d rows | nominal metrics %d/%d available, ' ...
     '%d/%d valid | condition-specific metrics %d/%d available, %d/%d valid.'], ...
    row_count, ...
    nominal_available,row_count, ...
    nominal_valid,row_count, ...
    condition_available,row_count, ...
    condition_valid,row_count);

if nominal_available < row_count || condition_available < row_count
    study_log('line', ...
        ['Unavailable scientific metric values are stored in the tables ' ...
         'as NaN and appear as gaps in figures.']);
end

end
