function output = generate_sensitivity_outputs()
%GENERATE_SENSITIVITY_OUTPUTS Study 4 selected sensitivity reporting.
%
% The complete sensitivity tables and diagnostics are exported, while
% figures are generated only for the metric-condition combinations used in
% the manuscript. Raw-value figures report physical performance quantities
% in their natural signs. Percentage-change figures are generated for the
% same selected combinations.

specifications = sensitivity_plot_specifications();
table_output_count = 7;
context = create_output_context('sensitivity', ...
    'Study 4: Assumption sensitivity', ...
    '04_assumption_sensitivity','Outputs 04', ...
    2*numel(specifications)+table_output_count);

logger = context.logger;
completed = strings(0,1);

try
    required = {context.files.design_manifest;context.files.sensitivity_manifest; ...
        context.files.rotorwise_designs; ...
        context.files.nominal_sensitivity; ...
        context.files.condition_specific_sensitivity_summary; ...
        context.files.condition_specific_sensitivity_repeatability; ...
        context.files.condition_specific_sensitivity_runs};

    require_output_files(required,context.title);

    design_provenance = assert_completed_stage( ...
        context.files.design_manifest,'design_comparison', ...
        context.parameters,context.solver);

    assert_completed_stage( ...
        context.files.sensitivity_manifest, ...
        'sensitivity',context.parameters,context.solver,design_provenance);

    nominal_results = load_result_table( ...
        context.files.nominal_sensitivity);

    condition_results = load_result_table( ...
        context.files.condition_specific_sensitivity_summary);

    repeatability = load_result_table( ...
        context.files.condition_specific_sensitivity_repeatability);

    optimization_runs = load_result_table( ...
        context.files.condition_specific_sensitivity_runs);

    matrix = sensitivity_summary_table( ...
        nominal_results,condition_results,context.solver);

    validate_sensitivity_outputs( ...
        matrix,context.parameters,context.solver);
    log_sensitivity_matrix_status(matrix);

    relative_matrix = sensitivity_relative_matrix_table(matrix);
    curve_summary = sensitivity_curve_summary_table( ...
        matrix,context.parameters);
    relative_curve_summary = sensitivity_relative_summary_table(matrix);

    context.paths = reset_study_output_paths(context.paths);

    % Generate only the raw-value panels selected for the manuscript.
    for index = 1:numel(specifications)
        specification = specifications(index);
        data = sensitivity_matrix_plot_data(matrix,specification);

        description = sprintf('figure: %s / %s', ...
            specification.analysis,specification.metric);

        [logger,completed] = run_output_figure_with_data( ...
            logger,completed,description, ...
            @() build_sensitivity_matrix_figure(data,specification), ...
            context.paths.figures,specification.output_name);
    end

    % Generate percentage-change versions for the same selected panels.
    for index = 1:numel(specifications)
        specification = specifications(index);

        data = sensitivity_relative_plot_table( ...
            matrix,specification.analysis,specification.metric, ...
            specification.parameter_source,specification.parameter_name);

        description = sprintf('relative figure: %s / %s', ...
            specification.analysis,specification.metric);

        [logger,completed] = run_output_figure_with_data( ...
            logger,completed,description, ...
            @() build_sensitivity_relative_figure(data,specification), ...
            context.paths.figures,[specification.output_name '_relative']);
    end

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: complete sensitivity matrix', ...
        matrix, ...
        context.paths.tables, ...
        'sensitivity_matrix');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: relative sensitivity matrix', ...
        relative_matrix, ...
        context.paths.tables, ...
        'sensitivity_matrix_relative');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: sensitivity curve summary', ...
        curve_summary, ...
        context.paths.tables, ...
        'sensitivity_curve_summary');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: relative sensitivity curve summary', ...
        relative_curve_summary, ...
        context.paths.tables, ...
        'sensitivity_curve_summary_relative');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'table: directionality sensitivity', ...
        sensitivity_directionality_table(matrix), ...
        context.paths.tables, ...
        'sensitivity_directionality');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'diagnostic: optimization repeatability', ...
        repeatability, ...
        context.paths.diagnostics, ...
        'condition_specific_repeatability');

    [logger,completed] = run_output_table( ...
        logger,completed, ...
        'diagnostic: optimization runs', ...
        optimization_runs, ...
        context.paths.diagnostics, ...
        'condition_specific_design_runs');

    relative_names = string({specifications.output_name}).' + "_relative";

    expected = [ ...
        string({specifications.output_name}).'; ...
        relative_names; ...
        "sensitivity_matrix"; ...
        "sensitivity_matrix_relative"; ...
        "sensitivity_curve_summary"; ...
        "sensitivity_curve_summary_relative"; ...
        "sensitivity_directionality"; ...
        "condition_specific_repeatability"; ...
        "condition_specific_design_runs"];

    require_completed_outputs( ...
        completed,expected,context.title);

    context.logger = logger;

    output = finish_output_study( ...
        context,logger,completed);

catch ME
    study_log('error',ME);
    rethrow(ME);
end

end


