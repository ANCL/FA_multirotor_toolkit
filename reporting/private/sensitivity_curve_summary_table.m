function T = sensitivity_curve_summary_table(all_cases,parameters)
%SENSITIVITY_CURVE_SUMMARY_TABLE Extrema and redesign summary for each cell.
specs = matrix_specs(parameters);

rows = repmat(struct('analysis',"",'objective',"", ...
    'physical_parameter',"",'number_of_points',0, ...
    'nominal_available_points',0,'nominal_valid_points',0, ...
    'condition_specific_available_points',0, ...
    'condition_specific_valid_points',0,'comparable_points',0, ...
    'baseline_parameter_value',NaN,'baseline_nominal_value',NaN, ...
    'nominal_minimum',NaN,'parameter_at_nominal_minimum',NaN, ...
    'nominal_maximum',NaN,'parameter_at_nominal_maximum',NaN, ...
    'condition_specific_minimum',NaN, ...
    'parameter_at_condition_specific_minimum',NaN, ...
    'condition_specific_maximum',NaN, ...
    'parameter_at_condition_specific_maximum',NaN, ...
    'maximum_improvement',NaN,'parameter_at_maximum_improvement',NaN), ...
    height(specs),1);

for index = 1:height(specs)
    selected = string(all_cases.analysis)==specs.analysis(index) & ...
        string(all_cases.objective)==specs.objective(index);
    family = all_cases(selected,:);
    if isempty(family)
        error('fa:MissingSensitivitySummary', ...
            'No sensitivity rows were found for %s/%s.', ...
            specs.analysis(index),specs.objective(index));
    end
    parameter = reported_parameter(family);

    baseline = specs.baseline_parameter_value(index);
    [baseline_error,baseline_index] = min(abs(parameter-baseline));
    baseline_tolerance = 100*eps(max(1,abs(baseline)));
    if baseline_error > baseline_tolerance
        error('fa:MissingSensitivityBaseline', ...
            'The exact baseline value is missing for %s/%s.', ...
            specs.analysis(index),specs.objective(index));
    end

    [nominal_minimum,nominal_minimum_index] = ...
        finite_extreme(family.nominal_geometry,'min');
    [nominal_maximum,nominal_maximum_index] = ...
        finite_extreme(family.nominal_geometry,'max');
    [condition_minimum,condition_minimum_index] = ...
        finite_extreme(family.condition_specific_optimum,'min');
    [condition_maximum,condition_maximum_index] = ...
        finite_extreme(family.condition_specific_optimum,'max');
    [maximum_improvement,maximum_improvement_index] = ...
        finite_extreme(family.condition_specific_improvement,'max');

    rows(index) = struct( ...
        'analysis',specs.analysis(index), ...
        'objective',specs.objective(index), ...
        'physical_parameter',string(family.physical_parameter(1)), ...
        'number_of_points',height(family), ...
        'nominal_available_points',sum(family.nominal_metric_available), ...
        'nominal_valid_points',sum(family.nominal_valid), ...
        'condition_specific_available_points', ...
            sum(family.condition_specific_metric_available), ...
        'condition_specific_valid_points',sum(family.condition_specific_valid), ...
        'comparable_points',sum(family.nominal_valid & family.condition_specific_valid), ...
        'baseline_parameter_value',parameter(baseline_index), ...
        'baseline_nominal_value',family.nominal_geometry(baseline_index), ...
        'nominal_minimum',nominal_minimum, ...
        'parameter_at_nominal_minimum',indexed_parameter(parameter,nominal_minimum_index), ...
        'nominal_maximum',nominal_maximum, ...
        'parameter_at_nominal_maximum',indexed_parameter(parameter,nominal_maximum_index), ...
        'condition_specific_minimum',condition_minimum, ...
        'parameter_at_condition_specific_minimum', ...
            indexed_parameter(parameter,condition_minimum_index), ...
        'condition_specific_maximum',condition_maximum, ...
        'parameter_at_condition_specific_maximum', ...
            indexed_parameter(parameter,condition_maximum_index), ...
        'maximum_improvement',maximum_improvement, ...
        'parameter_at_maximum_improvement', ...
            indexed_parameter(parameter,maximum_improvement_index));
end
T = struct2table(rows);
end

function parameter = reported_parameter(family)
parameter = family.parameter_value;
parameter = parameter(:);
end

function [value,index] = finite_extreme(values,mode)
finite_rows = find(isfinite(values));
if isempty(finite_rows)
    value = NaN;
    index = NaN;
    return;
end
finite_values = values(finite_rows);
switch mode
    case 'min'
        [value,local_index] = min(finite_values);
    case 'max'
        [value,local_index] = max(finite_values);
    otherwise
        error('fa:UnknownSummaryExtrema','Unknown extrema mode: %s.',mode);
end
index = finite_rows(local_index);
end

function value = indexed_parameter(parameter,index)
if isnan(index)
    value = NaN;
else
    value = parameter(index);
end
end

function specs = matrix_specs(parameters)
analyses = [ ...
    "actuator_capacity"; ...
    "hover_load"; ...
    "reaction_moment"; ...
    "directionality"; ...
    "characteristic_length"];
baselines = [1;1;parameters.kappa;0;parameters.force_moment_length];
metrics = string(parameters.sensitivity.matrix_metrics(:));

analysis = strings(numel(analyses)*numel(metrics),1);
objective = strings(size(analysis));
baseline_parameter_value = nan(size(analysis));
index = 0;
for family_index = 1:numel(analyses)
    for metric_index = 1:numel(metrics)
        index = index+1;
        analysis(index) = analyses(family_index);
        objective(index) = metrics(metric_index);
        baseline_parameter_value(index) = baselines(family_index);
    end
end
specs = table(analysis,objective,baseline_parameter_value);
end
