function T = sensitivity_curve_summary_table(all_cases,parameters)
%SENSITIVITY_CURVE_SUMMARY_TABLE Compact extrema and redesign summary.
baseline_task = diag(parameters.task.Lambda);
force_norm = norm(baseline_task(1:3),2);
moment_norm = norm(baseline_task(4:6),2);
rho_0 = moment_norm/(force_norm+moment_norm);

specs = table( ...
    ["task_emphasis";"actuator_capacity";"reaction_moment"; ...
     "characteristic_length";"characteristic_length"], ...
    ["q_star";"q_star";"q_star";"sigma_min";"condition_number"], ...
    [rho_0;1;parameters.kappa;parameters.force_moment_length; ...
     parameters.force_moment_length], ...
    'VariableNames',{'analysis','objective','baseline_parameter_value'});

rows = repmat(struct('analysis',"",'objective',"", ...
    'physical_parameter',"",'number_of_points',0, ...
    'baseline_parameter_value',NaN,'baseline_nominal_value',NaN, ...
    'nominal_minimum',NaN,'parameter_at_nominal_minimum',NaN, ...
    'nominal_maximum',NaN,'parameter_at_nominal_maximum',NaN, ...
    'condition_specific_minimum',NaN, ...
    'parameter_at_condition_specific_minimum',NaN, ...
    'condition_specific_maximum',NaN, ...
    'parameter_at_condition_specific_maximum',NaN, ...
    'maximum_improvement',NaN,'parameter_at_maximum_improvement',NaN), ...
    height(specs),1);

for index = 1:height(specs)
    selected = string(all_cases.analysis)==specs.analysis(index) & ...
        string(all_cases.objective)==specs.objective(index);
    family = all_cases(selected,:);
    if isempty(family)
        error('fa:MissingSensitivitySummary', ...
            'No sensitivity rows were found for %s/%s.', ...
            specs.analysis(index),specs.objective(index));
    end
    if specs.analysis(index)=="task_emphasis"
        parameter = family.rho;
    else
        parameter = family.parameter_value;
    end

    baseline = specs.baseline_parameter_value(index);
    [baseline_error,baseline_index] = min(abs(parameter-baseline));
    baseline_tolerance = 100*eps(max(1,abs(baseline)));
    if baseline_error > baseline_tolerance
        error('fa:MissingSensitivityBaseline', ...
            'The exact baseline value is missing for %s/%s.', ...
            specs.analysis(index),specs.objective(index));
    end
    [nominal_minimum,nominal_minimum_index] = min(family.nominal_geometry);
    [nominal_maximum,nominal_maximum_index] = max(family.nominal_geometry);
    [condition_minimum,condition_minimum_index] = ...
        min(family.condition_specific_optimum);
    [condition_maximum,condition_maximum_index] = ...
        max(family.condition_specific_optimum);
    [maximum_improvement,maximum_improvement_index] = ...
        max(family.condition_specific_improvement);

    rows(index) = struct( ...
        'analysis',specs.analysis(index), ...
        'objective',specs.objective(index), ...
        'physical_parameter',string(family.physical_parameter(1)), ...
        'number_of_points',height(family), ...
        'baseline_parameter_value',parameter(baseline_index), ...
        'baseline_nominal_value',family.nominal_geometry(baseline_index), ...
        'nominal_minimum',nominal_minimum, ...
        'parameter_at_nominal_minimum',parameter(nominal_minimum_index), ...
        'nominal_maximum',nominal_maximum, ...
        'parameter_at_nominal_maximum',parameter(nominal_maximum_index), ...
        'condition_specific_minimum',condition_minimum, ...
        'parameter_at_condition_specific_minimum', ...
            parameter(condition_minimum_index), ...
        'condition_specific_maximum',condition_maximum, ...
        'parameter_at_condition_specific_maximum', ...
            parameter(condition_maximum_index), ...
        'maximum_improvement',maximum_improvement, ...
        'parameter_at_maximum_improvement', ...
            parameter(maximum_improvement_index));
end
T = struct2table(rows);
end
