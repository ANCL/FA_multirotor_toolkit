function output = generate_objective_design_outputs()
%GENERATE_OBJECTIVE_DESIGN_OUTPUTS Study 1 reporting implementation.
context = create_output_context('objective_designs', ...
    'Study 1: Objective-dependent P1 designs', ...
    '01_objective_dependent_designs','Outputs 01',14);
logger = context.logger;
completed = strings(0,1);
try
    required = {context.files.objective_cross;context.files.rotorwise_designs; ...
        context.files.rotorwise_raw;context.files.rotorwise_repeatability; ...
        context.files.rotorwise_optimization_runs; ...
        context.files.task;context.files.task_raw};
    require_output_files(required,context.title);
    validate_optimization_result_set(context.files.rotorwise_raw);
    design_provenance = assert_compatible_result( ...
        context.files.rotorwise_designs,'design_comparison', ...
        context.parameters,context.solver);
    assert_compatible_result(context.files.task_raw, ...
        'task_evaluation',context.parameters,context.solver,design_provenance);

    cross_evaluation = load_result_table(context.files.objective_cross);
    task_summary = load_result_table(context.files.task);
    repeatability = load_result_table(context.files.rotorwise_repeatability);
    optimization_runs = load_result_table( ...
        context.files.rotorwise_optimization_runs);
    design_data = load(context.files.rotorwise_designs,'selected');
    validate_objective_outputs(cross_evaluation,task_summary);
    context.paths = reset_study_output_paths(context.paths);

    [logger,completed] = run_output_table(logger,completed, ...
        'table: objective cross-evaluation', ...
        objective_comparison_table(cross_evaluation,design_data.selected), ...
        context.paths.tables,'objective_cross_evaluation');
    [logger,completed] = run_output_table(logger,completed, ...
        'table: task verification',task_summary,context.paths.tables, ...
        'task_verification');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: objective repeatability',repeatability, ...
        context.paths.diagnostics,'objective_run_repeatability');
    [logger,completed] = run_output_table(logger,completed, ...
        'diagnostic: objective optimization runs',optimization_runs, ...
        context.paths.diagnostics,'objective_optimization_runs');

    plot_data = design_comparison_plot_data(context.root, ...
        context.parameters,context.solver);
    for index = 1:height(plot_data.specs)
        geometry_name = char(plot_data.specs.geometry_file(index));
        geometry_options = struct( ...
            'figure_position',context.style.dimensions.column_short, ...
            'view',[55 26]);
        [logger,completed] = run_output_figure(logger,completed, ...
            ['figure: ' geometry_name], ...
            @() plot_multirotor_configuration( ...
            plot_data.geometries{index},geometry_options), ...
            context.paths.figures,geometry_name);

        force_name = char(plot_data.specs.force_file(index));
        force_options = struct( ...
            'labels',[string(context.style.labels.force_set); ...
            string(context.style.labels.zero_moment_force_set)], ...
            'axis_labels',{{'$F_x$','$F_y$','$F_z$'}}, ...
            'colors',[context.style.colors.gray;context.style.colors.blue], ...
            'face_alpha',[context.style.alpha.surface_full; ...
            context.style.alpha.surface_restricted], ...
            'axis_limits',plot_data.force_limits(index,:), ...
            'figure_position',context.style.dimensions.column_short, ...
            'view',[55 26], ...
            'reference_point',plot_data.hover_force, ...
            'reference_label',context.style.labels.hover_force);
        [logger,completed] = run_output_figure(logger,completed, ...
            ['figure: ' force_name], ...
            @() plot_feasible_set( ...
            {plot_data.force_sets{index}.force, ...
            plot_data.force_sets{index}.zero_moment_force},force_options), ...
            context.paths.figures,force_name);
    end

    expected = ["objective_cross_evaluation";"task_verification"; ...
        "objective_run_repeatability";"objective_optimization_runs"; ...
        plot_data.specs.geometry_file;plot_data.specs.force_file];
    require_completed_outputs(completed,expected,context.title);
    context.logger = logger;
    output = finish_output_study(context,logger,completed);
catch ME
    study_log('error',ME);
    rethrow(ME);
end
end
